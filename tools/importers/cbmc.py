def generate(qp, p, proof, o):
    """The files of an imported law: (law, {relative path in projects/NAME: bytes}, info), a pure function of
    the upstream files at the pinned commit, the options, the shim and VERSION.  Raises Refused (with every
    reason) for a proof that cannot be translated."""
    if o.layout != 'starter-kit':
        raise Refused('the Makefile.json layout (FreeRTOS-Plus-TCP, the FreeRTOS kernel) is future work')
    proof = os.path.normpath(proof).strip('/')
    if proof.startswith('..') or os.path.isabs(proof):
        qp.die('PROOF_DIR must be a path in the upstream tree: %s' % proof)
    tree = os.path.realpath(qp.private_tree(p, False, '.cbmc'))
    pdir = os.path.join(tree, proof)
    if not os.path.isfile(os.path.join(pdir, 'Makefile')):
        qp.die('%s/Makefile: not in the upstream tree at %s (a cbmc-starter-kit proof directory; CODE in '
               'project.conf must cover the proof tree and the library)' % (proof, p.commit[:12]))
    root = pdir
    while root != tree and not os.path.isfile(os.path.join(root, 'Makefile.common')):
        root = os.path.dirname(root)
    if not os.path.isfile(os.path.join(root, 'Makefile.common')):
        raise Refused('no Makefile.common above %s: not a cbmc-starter-kit proof' % proof)
    cbmc_root = os.path.dirname(root)
    rel = lambda x: os.path.relpath(x, tree)
    reasons, warnings, notes, dropped = [], [], [], []
    # the directories the kit computes from make's own state ($(MAKEFILE_LIST), $(shell dirname ...)); SRCDIR is
    # the Makefiles' (Makefile-template-defines: three levels above the proof root), else the tree's root
    predefined = {'PROOFDIR': pdir, 'PROOF_ROOT': root, 'CBMC_ROOT': cbmc_root,
                  'PROOF_SOURCE': os.path.join(cbmc_root, 'sources'), 'PROOF_STUB': os.path.join(cbmc_root, 'stubs')}
    m0 = Make(pdir, predefined)
    m0.read(os.path.join(pdir, 'Makefile'))
    srcdir = os.path.realpath(m0.value('SRCDIR')) if m0.value('SRCDIR').strip() else tree
    if srcdir != tree and not srcdir.startswith(tree + os.sep):
        notes.append('SRCDIR of the Makefiles is outside the tree: the tree\'s root instead')
        srcdir = tree
    predefined['SRCDIR'] = srcdir
    # first without --set (the upstream values, for the claim), then with it
    m0 = Make(pdir, predefined)
    m0.read(os.path.join(pdir, 'Makefile'))
    fixed = dict(predefined)
    fixed.update({k: v for k, v in o.sets.items() if k in m0.assigned})
    mk = Make(pdir, fixed)
    mk.read(os.path.join(pdir, 'Makefile'))
    notes += [n.replace(tree + '/', '') for n in mk.notes]
    uid = ' '.join(mk.get('PROOF_UID')) or os.path.basename(pdir)
    entry = o.entry or ' '.join(mk.get('HARNESS_ENTRY')) or 'harness'
    law = o.law or re.sub(r'\W', '_', uid)
    if not re.fullmatch(r'[A-Za-z_]\w*', law):
        qp.die('law name %s is not a C identifier (--law)' % law)
    for v in ('CHECK_FUNCTION_CONTRACTS', 'CHECK_FUNCTION_CONTRACTS_REC', 'USE_FUNCTION_CONTRACTS',
              'APPLY_LOOP_CONTRACTS', 'USE_DYNAMIC_FRAMES'):
        if mk.get(v):
            reasons.append('%s is set: function and loop contracts (DFCC) are future work' % v)
    flags = tokens(mk.get('CBMCFLAGS') + mk.get('CHECKFLAGS'))
    flags += [t for k in sorted(mk.vars) if k.startswith('CBMC_FLAG_') for t in mk.get(k)]
    if mk.get('NONDET_STATIC') or '--nondet-static' in flags:
        reasons.append('--nondet-static (NONDET_STATIC): arbitrary initial values of static variables are future work')
    if any(f.startswith(('--restrict-function-pointer', '--function-pointer-restrictions')) for f in flags):
        reasons.append('--restrict-function-pointer: restricted function pointers have no plain-C counterpart')
    not_covered = [c for c in NOT_UB_CHECKS if c in flags and '--no-' + c[2:] not in flags]
    leaks = [c for c in LEAK_CHECKS if c in flags]
    malloc = o.malloc
    if malloc == 'auto':
        malloc = 'never-fails' if '--no-malloc-may-fail' in flags else 'may-fail'
    elif malloc == 'may-fail' and '--no-malloc-may-fail' in flags:
        warnings.append('the proof disables --malloc-may-fail; --malloc never-fails gives the CBMC meaning')
    if mk.get('UNWINDSET'):
        dropped.append('UNWINDSET %s' % ' '.join(mk.get('UNWINDSET')))
    cbflags = mk.get('CBMCFLAGS')
    for j, f in enumerate(cbflags):
        if f in ('--unwind', '--unwindset') and j + 1 < len(cbflags):
            dropped.append('%s %s' % (f, cbflags[j + 1]))
        elif f.startswith(('--unwind=', '--unwindset=')):
            dropped.append(f)
    if '--unwinding-assertions' in flags or not any('--no-unwinding-assertions' == f for f in flags):
        dropped.append('unwinding assertions')
    dropped = [d for d in dropped if d]

    # the sources: harness code (PROOF_SOURCES, and PROJECT_SOURCES under CBMC_ROOT) and library code
    def files_of(var):
        out = []
        for s in mk.get(var):
            s = os.path.realpath(s if os.path.isabs(s) else os.path.join(pdir, s))
            if s not in out:
                out.append(s)
        return out
    harness_src, lib_src, moved = [], [], []
    for s in files_of('PROOF_SOURCES'):
        harness_src.append(s)
    for s in files_of('PROJECT_SOURCES'):
        if s.startswith(cbmc_root + os.sep):
            if s not in harness_src:
                harness_src.append(s)
            moved.append(rel(s))
        elif s not in lib_src:
            lib_src.append(s)
    for s in harness_src + lib_src:
        if not s.startswith(tree + os.sep):
            reasons.append('source %s is outside the upstream tree' % s)
        elif not os.path.isfile(s):
            qp.die('%s: not in the upstream tree at %s (CODE in project.conf must cover it)' % (rel(s), p.commit[:12]))
    if moved:
        notes.append('PROJECT_SOURCES in the proof tree are harness code: ' + ', '.join(moved))
    if reasons:
        raise Refused('\n'.join(reasons))
    # harness files that are CBMC models of the C library: the framework's plain-C functions instead
    kept, replaced = [], []
    for s in harness_src:
        if os.path.dirname(s) != pdir:
            names = set(m.decode() for m in re.findall(rb'^[A-Za-z_][\w \t\*]*?\b(\w+)\s*\([^;{}]*\)\s*\{',
                                                       open(s, 'rb').read(), re.M))
            names = set(n for n in names if not n.startswith('__builtin___') and not n.endswith('_impl'))
            if names and names <= LIBC:
                replaced.append('%s (a CBMC model of %s)' % (rel(s), ', '.join(sorted(names))))
                continue
        kept.append(s)
    harness_src = kept

    # flags: the project's (quickproof.conf), the proof's includes and defines
    u_inc, u_defs, u_units, u_text = user_conf(qp, tree)
    inc_tokens = tokens(mk.get('INCLUDES'))
    proof_inc = []
    for t in inc_tokens:
        r, why = rel_include(t, tree)
        if r is None:
            warnings.append('include flag %s dropped (%s)' % (t.replace(tree + '/', ''), why))
        elif r not in proof_inc:
            proof_inc.append(r)
    for r in proof_inc:
        if not os.path.isdir(os.path.join(tree, r.split()[-1][2:] if r.startswith('-I') else r.split()[-1])):
            notes.append('include directory %s is not in the tree' % r)
    defines, bounds, sets_old = [], [], []
    upstream_defs = {}
    for t in tokens(m0.get('DEFINES')):
        nm, kind = define_name(t)
        if nm:
            upstream_defs[nm] = t.split('=', 1)[1] if '=' in t else ('1' if kind == 'D' else 'undefined')
    for t in tokens(mk.get('DEFINES')):
        nm, kind = define_name(t)
        if nm is None:
            warnings.append('DEFINES token %s ignored (not -D or -U)' % t)
            continue
        if nm in o.undef:
            notes.append('define %s dropped (--undef)' % t[2:])
            continue
        if nm in o.sets and kind == 'D':
            old = upstream_defs.get(nm, '1')
            if not any(s[0] == nm for s in sets_old):
                sets_old.append((nm, o.sets[nm], old))
            t = '-D%s=%s' % (nm, o.sets[nm])
        if t not in defines:
            defines.append(t)
    for k, v in o.sets.items():
        if any(s[0] == k for s in sets_old):
            continue
        if k in m0.assigned:                       # a make variable of the proof
            sets_old.append((k, v, m0.assigned[k]))
        elif not any(define_name(d)[0] == k for d in defines):
            defines.append('-D%s=%s' % (k, v))     # a macro the harness code defines itself, if not given
            sets_old.append((k, v, 'none: added'))
    fw_inc = os.path.join(FW_HOME, 'include')
    abs_inc = lambda xs: [('-I' + os.path.join(tree, x[2:])) if x.startswith('-I') else
                          x.split()[0] + ' ' + os.path.join(tree, x.split()[1]) for x in xs]
    split_inc = lambda xs: [y for x in xs for y in (x.split(' ', 1) if x.startswith('-i') else [x])]
    base = u_inc + split_inc(abs_inc(proof_inc)) + u_defs + ENV_DEFS
    wide, local = classify_defines(defines, lib_src, base, tree)

    # CBMC uninterpreted functions: an arbitrary value at each call
    texts = b''
    for s in harness_src:
        texts += open(s, 'rb').read()
    for r in proof_inc:
        d = os.path.join(tree, r[2:]) if r.startswith('-I') else os.path.join(tree, r.split()[-1])
        if os.path.realpath(d).startswith(cbmc_root):
            for dp, _, fs in sorted(os.walk(d)):
                for fn in sorted(fs):
                    if fn.endswith('.h'):
                        texts += open(os.path.join(dp, fn), 'rb').read()
    uninterp = sorted(set(n.decode() for n in re.findall(rb'__CPROVER_uninterpreted_(\w+)', texts)))
    uninterp_defs = ['-D__CPROVER_uninterpreted_%s(...)=qp_cbmc_uninterpreted_%s()' % (n, n) for n in uninterp]
    chk = []
    if b'__builtin___' in texts:
        chk = ['-D__builtin___%s_chk=qp_cbmc_unused_%s_chk' % (f, f) for f in
               ('memcpy', 'memmove', 'memset', 'strcpy', 'strncpy', 'strcat', 'strncat', 'sprintf', 'snprintf')]
    analysis_flags = base + wide + local + uninterp_defs + chk + ['-I' + fw_inc]
    shim_src = os.path.join(CBMC_DIR, SHIM)

    # REMOVE_FUNCTION_BODY
    lib_texts = [(s, open(s, 'rb').read()) for s in lib_src]
    harness_defs = set()
    for s in harness_src:
        for m in re.finditer(rb'^[^\S\n]*[A-Za-z_][^;{}()]*?\b(\w+)\s*\([^;{}]*\)\s*\{', open(s, 'rb').read(), re.M):
            harness_defs.add(m.group(1).decode())
    for f in mk.get('REMOVE_FUNCTION_BODY'):
        if f.startswith('__CPROVER_file_local_'):
            reasons.append('REMOVE_FUNCTION_BODY %s: a static function of the library (a patch is future work)' % f)
            continue
        pat = re.compile(rb'^[^\S\n]*[A-Za-z_][^;{}()]*\b' + re.escape(f.encode()) + rb'\s*\([^;{}]*\)\s*\{', re.M)
        in_lib = [rel(s) for s, t in lib_texts if pat.search(t)]
        if not in_lib:
            notes.append('REMOVE_FUNCTION_BODY %s: no body in the library code, nothing to remove%s'
                         % (f, ' (the harness code defines it)' if f in harness_defs else ''))
        elif f in harness_defs:
            reasons.append('REMOVE_FUNCTION_BODY %s: the library defines it (%s) and the harness code replaces it: '
                           'a patch that drops the library definition is future work' % (f, ', '.join(in_lib)))
        else:
            reasons.append('REMOVE_FUNCTION_BODY %s: the library defines it (%s); CBMC gives it an arbitrary '
                           'result: a generated stub and a patch are future work' % (f, ', '.join(in_lib)))

    # the harness code: refused constructs (in the preprocessed text, so that macros of headers count too)
    names_used = {}
    for s in harness_src:
        cur = rel(s)
        for line in clang_preprocess(s, analysis_flags, shim_src, tree).split('\n'):
            m = re.match(r'^# (\d+) "([^"]+)"', line)
            if m:
                cur = m.group(2).replace(tree + '/', '')
                continue
            for name in set(re.findall(r'\b__CPROVER_\w+', line)):
                if name not in ALLOWED_CPROVER:
                    names_used.setdefault(name, set()).add(cur)
    lib_dirs = [os.path.join(tree, x[2:]) for x in proof_inc if x.startswith('-I')]
    lib_dirs = [d for d in lib_dirs + [os.path.join(tree, x[2:]) for x in u_inc if x.startswith('-I')]
                if os.path.isdir(d) and not os.path.realpath(d).startswith(cbmc_root + os.sep)]

    def macro_origin(name, files):
        """Library headers that spell `name` when the harness files do not (it came through a macro)."""
        if any(name in open(os.path.join(tree, f), errors='replace').read() for f in files
               if os.path.isfile(os.path.join(tree, f))):
            return []
        hits = []
        for d in sorted(set(lib_dirs)):
            for dp, _, fs in sorted(os.walk(d)):
                for fn in sorted(fs):
                    if fn.endswith(('.h', '.inl')) and name in open(os.path.join(dp, fn), errors='replace').read():
                        hits.append(rel(os.path.join(dp, fn)))
        return sorted(set(hits))[:3]
    for name in sorted(names_used):
        where = sorted(names_used[name])
        lib_hint = ''
        origin = macro_origin(name, where)
        if origin or any(not os.path.realpath(os.path.join(tree, w)).startswith(cbmc_root + os.sep) for w in where):
            lib_hint = (' (through a macro of the library\'s %s: a CBMC-only branch of the library? --undef builds the '
                        'library as for production)' % ', '.join(origin or where))
        if name in MEM_PREDICATES:
            if not o.approx_mem_predicates:
                reasons.append('uses %s (%s): pointer validity has no plain-C counterpart; --approx-mem-predicates '
                               'replaces it by true inside assertions and assumptions%s'
                               % (name, ', '.join(where), lib_hint))
            continue
        why = next((w for pre, w in REFUSED_CPROVER if name.startswith(pre)), 'a CBMC built-in the importer does not know')
        reasons.append('uses %s (%s): %s%s' % (name, ', '.join(where), why, lib_hint))
    # the AST of each harness source: one pass (C declares a type before its use), its own Types (clang's ids
    # are per run); the havoc functions are keyed by the type's name, the same in every source
    analyses = []
    for s in harness_src:
        an = Analysis(s, rel(s), Types(), cbmc_root)
        try:
            an.run(clang_ast(s, analysis_flags, shim_src, tree))
        except Refused as e:
            reasons.append(str(e))
            continue
        analyses.append(an)
    if len(analyses) < len(harness_src):
        raise Refused('\n'.join(dict.fromkeys(reasons)))
    approx, defined, used = [], {}, set()
    for an in analyses:
        reasons += an.refusals
        warnings += an.warnings
        for k, v in an.defined.items():
            defined.setdefault(k, v)
        used |= an.used
        approx += an.mem_contexts
    for f in mk.get('REMOVE_FUNCTION_BODY'):         # a body in a library header (a static inline function)
        where = defined.get(f)
        if where and not os.path.realpath(where).startswith(cbmc_root + os.sep) and \
                not any(r.startswith('REMOVE_FUNCTION_BODY %s:' % f) for r in reasons):
            reasons.append('REMOVE_FUNCTION_BODY %s: the library defines it in a header (%s): a patch that drops the '
                           'library definition is future work' % (f, rel(os.path.realpath(where))))
    if o.approx_mem_predicates:
        for pname, ctx in approx:
            if ctx == 'other':
                reasons.append('%s outside an assertion or assumption (a condition, an argument, a negation): '
                               'replacing it by true would change the control flow' % pname)
    generated = set(n for an in analyses for n in an.nondet) | set('qp_cbmc_uninterpreted_' + n for n in uninterp)
    unproto = sorted(set(n for an in analyses for n in an.unproto_calls) - generated - QP_ENV_NAMES)
    if unproto:
        warnings.append('called through a declaration without a prototype (CompCert\'s semantics makes such a call '
                        'undefined: the law fails there until the harness code declares a prototype): ' + some(unproto))
    harness_files = set(os.path.realpath(s) for s in harness_src)
    entry_an = next((an for an in analyses if os.path.realpath(defined.get(entry) or '') == an.src), None)
    if entry_an is None:
        reasons.append('the entry function %s is not defined in the harness code' % entry)
    if 'main' in defined and os.path.realpath(defined['main'] or '') in harness_files:
        reasons.append('the harness code defines main')
    # body-less nondet_* functions used by the harness code, and uninterpreted functions: any value
    value_protos, value_defs, done_values = [], [], set()
    for an in analyses:
        for name in sorted(an.nondet):
            if name in QP_ENV_NAMES or name not in used or name in defined or name in done_values:
                continue
            done_values.add(name)
            qt, implicit = an.nondet[name]
            try:
                sig, d = value_function(name, qt, an.types, 'nondet function')
            except Refused as e:
                reasons.append(str(e))
                continue
            if early(sig, name):
                value_protos.append(sig + ';')
            elif implicit or qt.endswith('()'):
                warnings.append('%s is declared without a prototype and its type cannot be declared before the '
                                'harness code: CompCert\'s semantics makes such a call undefined' % name)
            value_defs.append(d)
    uninterp_used = [n for n in uninterp if 'qp_cbmc_uninterpreted_' + n in used]
    for n in uninterp_used:
        fn = 'qp_cbmc_uninterpreted_' + n
        an = next((a for a in analyses if fn in a.uninterp), analyses[0] if analyses else None)
        qt = an.uninterp.get(fn, 'int ()') if an else 'int ()'
        try:
            sig, d = value_function(fn, qt, an.types if an else Types(), 'uninterpreted function')
        except Refused as e:
            reasons.append(str(e))
            continue
        if early(sig, fn):
            value_protos.append(sig + ';')
        else:
            warnings.append('uninterpreted function %s: its type cannot be declared before the harness code: '
                            'CompCert\'s semantics makes its calls undefined' % n)
        value_defs.append(d)
        warnings.append('uninterpreted function %s: an arbitrary value at each call (CBMC: the same value for '
                        'the same arguments)' % n)
    # main: the entry, with arbitrary arguments
    main_lines, arg_names = [], []
    if entry_an is not None:
        for i, (pn, pt) in enumerate(entry_an.entry_params.get(entry, [])):
            if '(' in pt or '[' in pt:
                reasons.append('parameter %s of %s has type %s: not supported' % (pn, entry, pt))
                continue
            a = 'qp_arg%d' % i
            main_lines.append('\t%s %s;' % (pt, a))
            main_lines += ['\t' + l for l in entry_an.types.havoc(a, pt, '%s:%s' % (entry, pn))]
            arg_names.append(a)
    protos, typed_defs, done = [], [], set()
    for an in analyses:
        pr, df = an.types.functions(done)
        protos += pr
        typed_defs += df
    for an in analyses:
        reasons += an.types.refusals
        warnings += an.types.warnings
    if reasons:
        raise Refused('\n'.join(dict.fromkeys(reasons)))
    warnings = list(dict.fromkeys(warnings))

    # the files
    shim_t = open(shim_src, 'rb').read()
    shim = ('/* Generated by tools/qp import-cbmc (importer version %d): a copy of tools/cbmc/%s\n'
            ' * (sha256 %s); do not edit, any import into this project rewrites it. */\n'
            % (VERSION, SHIM, sha256(shim_t))).encode() + shim_t
    files = {'harness/cbmc/%s' % SHIM: shim}
    names, sources, edits_l = {}, [], []
    for an in analyses:
        base_ = os.path.basename(an.src)
        if base_ in names.values():
            base_ = re.sub(r'\W', '_', os.path.basename(os.path.dirname(an.src))) + '_' + base_
        names[an.src] = base_
        old = open(an.src, 'rb').read()
        new = rewrite(old, an.inserts, an.replaces)
        # quoted includes of headers next to the original file: the copy lives elsewhere
        d_orig = os.path.dirname(an.src)
        copy_dir = os.path.join(tree, 'harness', 'cbmc', law)

        def fix_inc(m):
            h = m.group(2).decode()
            if os.path.isfile(os.path.join(d_orig, h)):
                newp = os.path.relpath(os.path.join(d_orig, h), copy_dir)
                an.edits.append('#include "%s" -> "%s"' % (h, newp))
                return m.group(1) + newp.encode() + m.group(3)
            return m.group(0)
        new = re.sub(rb'^(\s*#\s*include\s*")([^"]+)(")', fix_inc, new, flags=re.M)
        hdr = ('/* Generated by tools/qp import-cbmc (importer version %d) from\n * %s\n * (sha256 %s):\n'
               ' * the harness code, with an arbitrary value given to each uninitialised local (QP_CBMC_HAVOC*, after\n'
               ' * its declaration) and typed allocations, as listed in the law harness/%s.c.  Do not edit. */\n'
               '#line 1 "%s"\n' % (VERSION, an.rel, sha256(old), law, an.rel)).encode()
        files['harness/cbmc/%s/%s' % (law, base_)] = hdr + new
        sources.append((an.rel, sha256(old), base_))
        for fn, var, qt, mac in an.locals:
            edits_l.append('%s:%s:%s=%s' % (base_, fn, var, mac))
        edits_l += ['%s: %s' % (base_, e) for e in an.edits]
    rel_lib = [rel(s) for s in lib_src]
    makefiles = [(rel(f), sha256(open(f, 'rb').read())) for f in mk.files]
    own = Make(pdir, fixed, follow=False)
    own.read(os.path.join(pdir, 'Makefile'))
    own_names = set(define_name(t)[0] for t in tokens(own.get('DEFINES'))) | set(o.sets)
    bound_names = [d[2:] for d in wide + local if define_name(d)[1] == 'D' and define_name(d)[0] in own_names]
    claim_t = claim(proof, entry, o, malloc, bound_names, sets_old, o.undef, approx if o.approx_mem_predicates else [],
                    uninterp_used, not_covered, leaks)
    cmd = ['tools/qp', 'import-cbmc', p.name, proof, '--law', law]
    if o.entry:
        cmd += ['--entry', o.entry]
    cmd += ['--malloc', o.malloc]
    for k, v in o.sets.items():
        cmd += ['--set', shlex.quote('%s=%s' % (k, v))]
    for u in o.undef:
        cmd += ['--undef', u]
    if o.approx_mem_predicates:
        cmd.append('--approx-mem-predicates')
    if o.no_env:
        cmd.append('--no-env')
    opts = ['malloc=%s%s' % (malloc, ' (auto)' if o.malloc == 'auto' else ''),
            'mem-predicates=%s' % ('approx' if o.approx_mem_predicates else 'refuse'),
            'set=%s' % (','.join('%s=%s' % kv for kv in o.sets.items()) or '-'),
            'undef=%s' % (','.join(o.undef) or '-'), 'env=%s' % ('no' if o.no_env else 'cbmc_values')]
    q = lambda xs: [shlex.quote(x) for x in xs]
    L = [cblock(claim_t), '',
         '/* %s (generated; do not edit; regenerate with the command below)' % MARK,
         ' *   %-15s tools/qp import-cbmc, version %d' % ('importer:', VERSION),
         ' *   %-15s %s' % ('command:', ' '.join(cmd)),
         ' *   %-15s %s' % ('upstream:', p.upstream_conf),
         ' *   %-15s %s' % ('commit:', p.commit),
         ' *   %-15s %s' % ('proof:', proof),
         ' *   %-15s %s' % ('entry:', entry)]
    for f, h in makefiles:
        L.append(' *   %-15s %s sha256 %s' % ('makefile:', f, h))
    for r_, h, b in sources:
        L.append(' *   %-15s %s sha256 %s -> harness/cbmc/%s/%s' % ('source:', r_, h, law, b))
    for r_ in replaced:
        L += field_lines('replaced', [r_ + ': the framework\'s plain-C C library'])
    L.append(' *   %-15s harness/cbmc/%s sha256 %s' % ('shim:', SHIM, sha256(shim)))
    L += field_lines('options', opts)
    L += field_lines('units', rel_lib or ['-'])
    L += field_lines('includes', q(proof_inc) or ['-'])
    L += field_lines('defines', q(wide) or ['-'])
    L += field_lines('local', q(local) or ['-'])
    L += field_lines('dropped', [d + (';' if i + 1 < len(dropped) else '') for i, d in enumerate(dropped)] or ['-'])
    L += field_lines('edits', edits_l or ['-'])
    for w in warnings:
        L += field_lines('warning', [w])
    for n_ in notes:
        L += field_lines('note', [n_])
    L += [' * The sha256 are of the upstream files at the commit; the project\'s PATCH, if any, applies to the library.',
          ' * `units`, `includes` and `defines` configure the library for the whole project (the importer\'s block',
          ' * of quickproof.conf); `local` are the proof\'s defines that only the harness code sees (below).',
          ' * Replay protocol: the havoc sites (`edits`, FILE:FUNCTION:VARIABLE) draw in program order. */']
    L.append('')
    if local:
        L.append('/* The proof\'s defines that do not change the library code (law-local). */')
        L += [define_line(d) for d in local]
    if uninterp or chk:
        L.append('/* CBMC\'s uninterpreted functions and fortified builtins (see the claim). */')
        L += [define_line(d) for d in uninterp_defs + chk]
    L.append('#define QP_CBMC_MALLOC %s' % ('QP_CBMC_MALLOC_MAY_FAIL' if malloc == 'may-fail'
                                            else 'QP_CBMC_MALLOC_NEVER_FAILS'))
    if o.approx_mem_predicates:
        L.append('#define QP_CBMC_APPROX_MEM_PREDICATES 1')
    L.append('#include "cbmc/%s"' % SHIM)
    if value_protos or protos:
        L += ['', '/* Declared before the harness code, defined after it (where its types are complete). */']
        L += value_protos + protos
    L += ['', '/* The harness code, rewritten only as listed above. */']
    for _, _, b in sources:
        L.append('#include "cbmc/%s/%s"' % (law, b))
    if value_defs:
        L += ['', '/* The body-less nondet_* and uninterpreted functions of the harness: any value of the return '
                  'type. */']
        L += [d + '\n' for d in value_defs]
        L[-1] = L[-1].rstrip('\n')
    if typed_defs:
        L += ['', '/* Arbitrary values of the harness\'s structs, field by field (_Bool 0 or 1, pointers NULL or '
                  'invalid). */']
        L += [d + '\n' for d in typed_defs]
        L[-1] = L[-1].rstrip('\n')
    L += ['', 'int main(void)', '{'] + main_lines + \
         ['\t%s(%s);' % (entry, ', '.join(arg_names)),
          '\tqp_assert(1);        /* the end is reached: a marker for the non-vacuity gate (trivially true) */',
          '\treturn 0;', '}', '']
    files['harness/%s.c' % law] = '\n'.join(L).encode()
    if not o.no_env:
        vt = open(os.path.join(CBMC_DIR, VALUES), 'rb').read()
        files['env/%s.c' % law] = ('/* %s (importer version %d): a copy of tools/cbmc/%s (sha256 %s), the value\n'
                                   ' * distribution of law %s for native and interpreter runs (testing only). Replace '
                                   'it by a\n * hand-written file to keep it. */\n'
                                   % (VALUES_MARK, VERSION, VALUES, sha256(vt), law)).encode() + vt
    info = dict(units=rel_lib, includes=proof_inc, defines=wide, law=law, warnings=warnings, notes=notes,
                user=(u_inc, u_defs, u_units, u_text), replaced=replaced, locals=edits_l)
    return law, files, info


def write(qp, p, law, files, info):
    """Write the files (only those that changed) and the importer's block of quickproof.conf."""
    dst = os.path.join(p.dir, 'harness', law + '.c')
    if os.path.exists(dst) and MARK.encode() not in open(dst, 'rb').read():
        qp.die('%s exists and is not an imported CBMC law; choose another --law' % dst)
    envp = os.path.join(p.dir, 'env', law + '.c')
    if 'env/%s.c' % law in files and os.path.exists(envp) and VALUES_MARK.encode() not in open(envp, 'rb').read(400):
        print('kept %s (hand-written)' % os.path.relpath(envp, qp.WORKSPACE))
        del files['env/%s.c' % law]
    # the law's copy of the harness code: stale generated files go
    d = os.path.join(p.dir, 'harness', 'cbmc', law)
    if os.path.isdir(d):
        for f in sorted(os.listdir(d)):
            rp = 'harness/cbmc/%s/%s' % (law, f)
            if rp not in files and os.path.isfile(os.path.join(d, f)) and \
                    b'Generated by tools/qp import-cbmc' in open(os.path.join(d, f), 'rb').read(200):
                os.remove(os.path.join(d, f))
                print('removed %s' % os.path.relpath(os.path.join(d, f), qp.WORKSPACE))
    for rel_, data in sorted(files.items()):
        path = os.path.join(p.dir, rel_)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        old = open(path, 'rb').read() if os.path.exists(path) else None
        if old != data:
            open(path, 'wb').write(data)
        print('%s %s' % ('unchanged' if old == data else 'wrote', os.path.relpath(path, qp.WORKSPACE)))
    conf = os.path.join(p.dir, qp.CONF)
    text = open(conf).read()
    u_inc, u_defs, u_units, u_text = info['user']
    user_text = re.sub(r'\n?# >>> qp import-cbmc:[^\n]*\n.*?' + re.escape(CONF_END) + r'\n', '\n', text, flags=re.S)
    new_text, conflicts, warns = conf_block(qp, p, user_text, u_inc, u_defs, u_units)
    for w in warns:
        print('warning: ' + w)
    if new_text != text:
        open(conf, 'w').write(new_text)
        added = [u for u in info['units'] if u not in text]
        print('updated %s (imported CBMC laws%s)' % (os.path.relpath(conf, qp.WORKSPACE),
                                                      ': library units added: ' + ', '.join(added) if added else ''))


def cone_check(qp, p, law):
    """The law's program through tools/clight.sh, as `qp assemble` translates it, and the Clight audit of the
    law's cone (tools/clight_audit.py: VST blockers, externals the cone calls).  When clight.sh fails because a
    library unit passes or returns structs by value, the units are translated again with clightgen's
    -fstruct-passing, so that the cone can still be audited (a blocker if such a function is in the cone);
    the project then needs an idiom patch before `qp assemble`, and the report says so."""
    tree = qp.private_tree(p, True, '.cbmccone')
    out = []
    r = qp.sh([qp.FW + '/tools/clight.sh', qp.CONF], cwd=tree, coq=True, check=False, capture=True)
    if r.returncode:
        errs = [l for l in (r.stdout or '').splitlines() if 'error' in l.lower()]
        if not errs or not all('struct' in l or 'errors detected' in l for l in errs):
            return ['clightgen failed (tools/clight.sh):'] + errs[:12]
        out.append('tools/clight.sh fails on the project as configured (an idiom patch is needed before `qp assemble`): '
                   + ' | '.join(sorted(set(re.sub(r'^\S+:\d+: ', '', l) for l in errs if 'errors detected' not in l)))
                   + '; units with these functions: ' + ', '.join(sorted(set(l.split(':')[0] for l in errs
                                                                               if ':' in l and 'detected' not in l))))
        wrap = tempfile.mkdtemp(prefix='qp-cbmc-clightgen.')
        try:
            path = qp.opam_env().get('PATH', os.environ.get('PATH', ''))
            real = shutil.which('clightgen', path=path)
            if not real:
                return out + ['clightgen not found']
            open(os.path.join(wrap, 'clightgen'), 'w').write(
                '#!/bin/sh\nfor a in "$@"; do [ "$a" = -E ] && exec %s "$@"; done\nexec %s -fstruct-passing "$@"\n'
                % (shlex.quote(real), shlex.quote(real)))
            os.chmod(os.path.join(wrap, 'clightgen'), 0o755)
            r = qp.sh([qp.FW + '/tools/clight.sh', qp.CONF], cwd=tree, coq=True, check=False, capture=True,
                      env={'PATH': wrap + os.pathsep + path})
        finally:
            shutil.rmtree(wrap, ignore_errors=True)
        if r.returncode:
            return out + ['clightgen failed also with -fstruct-passing:'] + \
                [l for l in (r.stdout or '').splitlines() if 'error' in l.lower()][:12]
        out.append('audited after a translation with -fstruct-passing (functions outside the cone may take structs)')
    res = qp.clight_audit_tree(tree, [law])[law]
    bl = qp.clight_audit_module().blockers(res)
    out.append('cone: %d functions; %s' % (len(res['cone']), 'no VST blocker' if not bl else 'blockers: ' + '; '.join(
        sorted(set('%s: %s (%s)' % (cat, f, unit) for _, cat, f, unit, _ in bl)))))
    # globals the law's units declare without a definition and its cone never calls: a review item of the
    # contract (whole_prog_undefined), harmless (docs/LINKING.md), but each one calls for a look
    gp = os.path.realpath(os.path.join(tree, qp.FW))
    outs = [u.split('=', 1)[1] for u in qp.source(os.path.join(tree, qp.CONF), ['UNITS'], gp)['UNITS']]
    outs = [o for o in outs if not o.startswith('src/harness/') or o == 'src/harness/' + law]
    internal, external = set(), set()
    for o in outs:
        c = open(os.path.join(tree, o, 'code.v'), errors='replace').read()
        internal |= set(re.findall(r'^Definition f_(\w+) := \{\|', c, re.M))
        external |= set(re.findall(r'EF_external "(\w+)"', c))
    idle = sorted(x for x in external - internal - set(qp.ENV_EXTERNALS) - set(res['externals'])
                  if not x.startswith('__builtin_'))
    if idle:
        out.append('%d functions declared without a definition, never called by the cone (CBMC tolerates them; '
                   'the contract lists them in whole_prog_undefined): %s' % (len(idle), some(idle)))
    return out


def native_gate(qp, p, law, runs):
    """The law built natively as `qp fuzz` builds it (ASan/UBSan, its env file), run in gate mode: a failure
    (a signal: failing check or sanitizer report), or vacuity (an assume never satisfied, no assert reached).
    Functions without a definition anywhere (CBMC tolerates them) are listed and left unresolved: calling one
    fails the run."""
    tree = qp.private_tree(p, True, '.cbmcgate')
    n = qp.Native(tree)
    objs, err = n.lib_objs()
    if objs is None:
        return 'library build failed: ' + (err.strip().splitlines() or [''])[-1][:200], None
    ho = n.harness_obj(law)
    if not ho:
        r = qp.sh(['gcc', '-O0', '-w', '-fsyntax-only', '-Iharness', '-I' + qp.FW + '/include'] + n.defs + n.inc +
                  ['harness/%s.c' % law], cwd=tree, check=False, capture=True)
        return 'law build failed: ' + ' | '.join(l for l in (r.stdout or '').splitlines() if 'error' in l)[:300], None
    exe = os.path.join(n.b, 'gate_' + law)
    env_o = n.env_o(law)
    cmd = ['gcc'] + qp.SAN + [ho] + objs + [n.drv] + ([env_o] if env_o else []) + ['-o', exe]
    r = qp.sh(cmd, check=False, capture=True)
    undefined = sorted(set(re.findall(r"undefined reference to `([^']+)'", r.stdout or '')))
    if r.returncode:
        r = qp.sh(cmd + ['-Wl,--unresolved-symbols=ignore-all'], check=False, capture=True)
        if r.returncode:
            return 'link failed: ' + (r.stdout or '').strip()[-300:], None
    # an allocation the sanitizer cannot serve returns NULL, as the framework's malloc may (and CBMC's with
    # --malloc-may-fail); ASan's default is to stop the run
    env = dict(qp.NATIVE_ENV, GP_GATE='1')
    env['ASAN_OPTIONS'] = env.get('ASAN_OPTIONS', '') + ':allocator_may_return_null=1'
    native_gate.exe, native_gate.env = exe, env
    r = qp.sh([exe, str(runs), '1', '100000', '10'], check=False, capture=True, timeout=1800, env=env)
    out = r.stdout or ''
    fails = re.findall(r'^seed (\d+): signal (\d+)', out, re.M)
    m = re.search(r'completed (\d+) \(passed all assumes\), rejected (\d+)', out)
    reached = sum(int(x) for x in re.findall(r'assert #\d+ @\S+: reached (\d+)', out))
    sites = len(re.findall(r'assert #\d+ @\S+: reached', out))
    never = len(re.findall(r'never satisfied', out))
    tally = 'completed %s, rejected %s; %d assert sites reached %d times' % (
        m.group(1) if m else '?', m.group(2) if m else '?', sites, reached)
    if undefined:
        tally += '; %d undefined functions, never called in these runs: %s' % (len(undefined), some(undefined))
    if fails:
        one = qp.sh([exe, '1', fails[0][0], '0', '10'], check=False, capture=True, timeout=300, env=env).stdout or ''
        msg = re.search(r'(ERROR: \w+Sanitizer: [^\n]*|runtime error: [^\n]*)', one)
        msg = re.sub(r' on address 0x[0-9a-f]+ at pc 0x[0-9a-f]+ bp 0x[0-9a-f]+ sp 0x[0-9a-f]+', '', msg.group(1)) \
            if msg else 'signal %s: a failing check' % fails[0][1]
        return 'FINDING: %d of %d runs fail, first seed %s (%s); %s' % (len(fails), runs, fails[0][0], msg[:160],
                                                                      tally), int(fails[0][0])
    if never or reached == 0:
        return 'VACUOUS in %d runs (%s); %s' % (runs, '%d assume(s) never satisfied' % never if never else
                                                 'no assert reached', tally), None
    return 'clean, non-vacuous (%d runs; %s)' % (runs, tally), None


def passing_seeds(qp, k, limit=300):
    """The first k seeds whose native run of the gate's binary passes every assumption and ends (for the
    interpreter: the same seed gives the same values there)."""
    exe, env = getattr(native_gate, 'exe', None), dict(getattr(native_gate, 'env', {}))
    env.pop('GP_GATE', None)
    out = []
    for seed in range(1, limit + 1):
        if not exe or len(out) >= k:
            break
        r = qp.sh([exe, '1', str(seed), '0', '10'], check=False, capture=True, timeout=120, env=env)
        if re.search(r'completed 1 \(passed all assumes\)', r.stdout or '') and 'FAILED 0' in (r.stdout or ''):
            out.append(seed)
    return out


def interp_seed(qp, p, law, seed, timeout=120):
    """The law under CompCert's interpreter on one seed of the native gate: the drivers and the law's env file
    derive the same values from a seed, so a native failure is replayed in the semantics of the theorem."""
    tree = qp.private_tree(p, True, '.cbmcseed')
    env = {'GP_INTERP_TIMEOUT': str(timeout)}
    if qp.env_file(tree, law):
        env['GP_ENV'] = os.path.join(tree, qp.env_file(tree, law))
    r = qp.sh([qp.FW + '/tools/interp.sh', qp.CONF, 'harness/%s.c' % law, str(seed), '1'], cwd=tree, check=False,
              capture=True, env=env, timeout=timeout + 600, coq=True)
    out = r.stdout or ''
    if re.search(r'runs 1: no stop \(0 skipped', out):
        return 'no stop on seed %d: the native failure is not undefined behaviour in CompCert\'s semantics' % seed
    if re.search(r'runs 1: no stop \(1 skipped', out):
        return 'seed %d timed out (%d s) under the interpreter' % (seed, timeout)
    m = re.search(r'Stuck state: (in function \w+, expression.*?)(?:\n\S|\Z)', out, re.S)
    return 'STOP at seed %d: %s' % (seed, ' '.join(m.group(1).split())[:200] if m else
                                     (out.strip().splitlines() or ['exit %d' % r.returncode])[-1][:200])


USAGE = ('qp import-cbmc NAME PROOF_DIR [--law L] [--entry FN] [--set NAME=VALUE].. [--undef NAME].. '
         '[--malloc auto|may-fail|never-fails] [--approx-mem-predicates] [--no-env] '
         '[--no-check] [--runs N] [--interp N] [--contract]')


def main(qp, p, proof, argv):
    o = options(qp, p, argv)
    if o.help:
        print('usage: ' + USAGE + '\n\nSee docs/IMPORT-CBMC.md.')
        return 0
    try:
        law, files, info = generate(qp, p, proof, o)
    except Refused as e:
        for r in str(e).split('\n'):
            print('refused: ' + r)
        print('qp import-cbmc: %s refused (nothing written)' % proof, file=sys.stderr)
        return 2
    # the block of quickproof.conf must stay consistent across the project's imported laws
    u_inc, u_defs, u_units, u_text = info['user']
    extra = (law, {'includes': [' '.join(shlex.quote(x) for x in info['includes'])],
                   'defines': [' '.join(shlex.quote(x) for x in info['defines'])],
                   'units': [' '.join(info['units'])]})
    _, conflicts, _ = conf_block(qp, p, u_text, u_inc, u_defs, u_units, extra)
    if conflicts:
        for c in conflicts:
            print('refused: ' + c)
        return 2
    write(qp, p, law, files, info)
    for w in info['warnings']:
        print('warning: ' + w)
    if o.no_check:
        return 0
    print('== the law\'s cone (tools/clight.sh, tools/clight_audit.py)', flush=True)
    print('\n'.join(cone_check(qp, p, law)), flush=True)
    seeds = []
    if o.runs > 0:
        print('== native gate (ASan/UBSan, %d runs, GP_GATE=1)' % o.runs)
        verdict, seed = native_gate(qp, p, law, o.runs)
        print(verdict, flush=True)
        if seed is not None and o.interp > 0:
            print('== interpreter on the failing seed %d' % seed, flush=True)
            print(interp_seed(qp, p, law, seed), flush=True)
        if o.interp > 0:
            seeds = passing_seeds(qp, o.interp)
    if o.interp > 0 and seeds:
        # the seeds that pass every assumption natively: random seeds mostly stop at a harness's assumptions
        print('== interpreter (%d seeds that pass every assumption natively: %s)'
              % (len(seeds), ' '.join(map(str, seeds))), flush=True)
        res = [interp_seed(qp, p, law, sd, 60) for sd in seeds]
        stops = [r_ for r_ in res if r_.startswith('STOP')]
        timeouts = sum(1 for r_ in res if 'timed out' in r_)
        print('\n'.join(stops) if stops else 'no stop (%d seeds%s)' % (
            len(seeds), ', %d timed out' % timeouts if timeouts else ''), flush=True)
    elif o.interp > 0:
        print('== interpreter (%d runs)' % o.interp, flush=True)
        qp.interp(p, [law], o.interp, 1800)
    if o.contract:
        out = os.path.join(qp.CACHE, 'cbmc-contract', '%s.%d' % (p.name, os.getpid()))
        shutil.rmtree(out, ignore_errors=True)
        qp.assemble(p, out)
        qp.sh('coq_makefile -f _CoqProject -o CoqMakefile', cwd=out, coq=True, capture=True)
        r = qp.sh(['make', '-f', 'CoqMakefile', '-j2', 'src/contracts/%s.vo' % law], cwd=out, coq=True, check=False,
                  capture=True)
        print('== contract src/contracts/%s.v: %s' % (law, 'builds' if r.returncode == 0 else 'FAILED\n' +
                                                      (r.stdout or '')[-2500:]))
        shutil.rmtree(out, ignore_errors=True)
    return 0
