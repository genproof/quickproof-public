INT_KINDS = {}
for _t in ('unsigned char', 'unsigned short', 'int', 'unsigned int', 'long', 'unsigned long', 'long long',
           'unsigned long long'):
    INT_KINDS[_t] = 'pick'
for _t in ('char', 'signed char'):
    INT_KINDS[_t] = 'schar'
INT_KINDS['short'] = 'short'
FLOATS = ('float', 'double', 'long double', '_Float16', '__float128', '_Float128', '__bf16')
ANON = re.compile(r'\((?:unnamed|anonymous) (struct|union|enum) at (.*?):(\d+):(\d+)\)')
QUALS = ('const', 'volatile', 'restrict', '__restrict', '__restrict__')


class Types:
    """Records, typedefs and enums of a translation unit, and the code that gives an lvalue an arbitrary value
    of its type (the typed havoc of DESIGN: field by field, recursively)."""

    def __init__(self):
        self.records = {}        # id -> dict(tag, name, fields, block, spell, loc)
        self.by_tag = {}         # (tag, name) -> id (complete definitions)
        self.by_loc = {}         # (file, line, col) -> id (unnamed records)
        self.typedefs = {}       # name -> ('rec', id) | ('enum',) | ('type', qualType)
        self.anon = {}           # token -> record id (for unnamed records in type strings)
        self.wanted = []         # record ids whose havoc functions are needed
        self.warnings = []
        self.refusals = []

    def record_decl(self, n, file_, block):
        if not n.get('completeDefinition'):
            return
        fields = []
        for c in n.get('inner', []) or []:
            if c.get('kind') == 'FieldDecl':
                t = c.get('type', {})
                fields.append((c.get('name') or '', t.get('qualType', ''), bool(c.get('isBitfield'))))
        rid = n['id']
        loc = n.get('loc', {})
        loc = loc.get('expansionLoc', loc)
        key = (os.path.realpath(file_) if file_ else '', loc.get('line'), loc.get('col'))
        self.records[rid] = dict(tag=n.get('tagUsed', 'struct'), name=n.get('name') or None, fields=fields,
                                 block=block, spell=None, loc=key)
        if n.get('name'):
            self.by_tag.setdefault((n.get('tagUsed', 'struct'), n['name']), rid)
            self.records[rid]['spell'] = '%s %s' % (n.get('tagUsed', 'struct'), n['name'])
        else:
            self.by_loc[key] = rid

    def typedef_decl(self, n):
        name = n.get('name')
        if not name or name in self.typedefs:
            return
        t = (n.get('inner') or [{}])[0]
        while t.get('kind') in ('ElaboratedType', 'ParenType') and t.get('inner'):
            owned = t.get('ownedTagDecl')
            if owned and owned.get('kind') == 'RecordDecl' and not owned.get('name'):
                self.anon_typedef(name, owned['id'])
                return
            t = t['inner'][0]
        if t.get('kind') == 'RecordType' and not (t.get('decl') or {}).get('name'):
            self.anon_typedef(name, t['decl']['id'])
            return
        if t.get('kind') == 'EnumType':
            self.typedefs[name] = ('enum',)
            return
        qt = n.get('type', {})
        self.typedefs[name] = ('type', qt.get('desugaredQualType') or qt.get('qualType', ''))

    def anon_typedef(self, name, rid):
        """typedef struct { ... } NAME: the record is spelled NAME in generated code."""
        self.typedefs[name] = ('rec', rid)
        if rid in self.records and not self.records[rid]['spell']:
            self.records[rid]['spell'] = name

    def anon_sub(self, t):
        def rep(m):
            key = (os.path.realpath(m.group(2)), int(m.group(3)), int(m.group(4)))
            rid = self.by_loc.get(key)
            tok = '@A%d' % len(self.anon)
            self.anon[tok] = rid
            return tok
        return ANON.sub(rep, t)

    def resolve(self, qt, depth=0):
        """A description of a type given as clang prints it: dict(k=kind, const=..., ...)."""
        t = self.anon_sub(qt.strip())
        if depth > 30:
            return dict(k='unknown', t=qt, const=False)
        if '(' in t:
            if re.search(r'\(\s*\*[^()]*\)\s*\(', t) or re.search(r'\(\s*\*[^()]*\[[^()]*\)\s*\(', t):
                if re.search(r'\(\s*\*[^()]*\[', t):
                    return dict(k='unknown', t=qt, const=False)
                return dict(k='fptr', const=bool(re.search(r'\(\s*\*\s*const\b', t)))
            if re.search(r'\(\s*\*[^()]*\)\s*\[', t):
                return dict(k='ptr', const=False)
            return dict(k='func', const=False)
        m = re.match(r'^(.*?)\s*\[([^\]]*)\]((?:\s*\[[^\]]*\])*)$', t)
        if m:
            elem = m.group(1) + m.group(3)
            return dict(k='array', elem=self.untok(elem), dim=m.group(2).strip(), const=False)
        words = t.replace('*', ' * ').split()
        trail = []
        while words and words[-1] in QUALS:
            trail.append(words.pop())
        if words and words[-1].endswith('*'):
            return dict(k='ptr', const='const' in trail)
        lead = []
        while words and words[0] in QUALS:
            lead.append(words.pop(0))
        const = 'const' in lead or 'const' in trail
        words = [w for w in words if w not in QUALS]
        base = ' '.join(words)
        if base.endswith('*'):
            return dict(k='ptr', const=const)
        m = re.match(r'^(struct|union|enum)\s+(\S+)$', base)
        if m:
            tag, name = m.groups()
            if tag == 'enum':
                return dict(k='enum', const=const)
            rid = self.anon[name] if name.startswith('@A') else self.by_tag.get((tag, name))
            if rid is None or rid not in self.records:
                return dict(k='incomplete', t='%s %s' % (tag, name if not name.startswith('@A') else '(unnamed)'),
                            const=const)
            return dict(k=self.records[rid]['tag'], rid=rid, const=const)
        if base in ('_Bool', 'bool'):
            return dict(k='bool', const=const)
        if base in INT_KINDS:
            return dict(k='int', how=INT_KINDS[base], spell=base, const=const)
        if base in ('__int128', 'unsigned __int128', '__int128_t', '__uint128_t'):
            return dict(k='int128', const=const)
        if base in FLOATS or base.startswith('_Complex'):
            return dict(k='float', const=const)
        if base == 'void':
            return dict(k='void', const=const)
        if base in self.typedefs:
            v = self.typedefs[base]
            if v[0] == 'rec':
                if v[1] not in self.records:
                    return dict(k='incomplete', t=base, const=const)
                return dict(k=self.records[v[1]]['tag'], rid=v[1], const=const)
            if v[0] == 'enum':
                return dict(k='enum', const=const)
            r = dict(self.resolve(v[1], depth + 1))
            r['const'] = r.get('const') or const
            return r
        return dict(k='unknown', t=base, const=const)

    def untok(self, s):
        """Type text with the unnamed-record tokens put back (for a recursive resolve)."""
        for tok, rid in self.anon.items():
            if tok in s and rid in self.records:
                f, l, c = self.records[rid]['loc']
                s = s.replace(tok, '(unnamed %s at %s:%s:%s)' % (self.records[rid]['tag'], f, l, c))
        return s

    def key(self, rid):
        """The C-identifier suffix of a record's havoc functions, or None (no file-scope spelling)."""
        r = self.records[rid]
        if r['block'] or not r['spell']:
            return None
        if r['name']:
            return '%s_%s' % (r['tag'], r['name'])
        return 'typedef_%s' % r['spell']

    def havoc(self, lhs, qt, where, depth=0, bitfield=False):
        """C statements that give the lvalue `lhs` (of type qt) an arbitrary value of its type."""
        if depth > 12:
            self.refusals.append('%s: type nested too deeply (%s)' % (where, qt))
            return []
        d = self.resolve(qt)
        k = d['k']
        if bitfield:
            if k == 'bool':
                return ['%s = (nondet_u8() & 1) != 0;' % lhs]
            return ['{ unsigned long qp_t; QP_CBMC_HAVOC(qp_t); %s = qp_t; }' % lhs]
        if k == 'int':
            if d['const']:
                return ['QP_CBMC_HAVOC_BYTES(%s);' % lhs]
            return ['%s(%s);' % ({'pick': 'QP_CBMC_HAVOC', 'schar': 'QP_CBMC_HAVOC_SCHAR',
                                  'short': 'QP_CBMC_HAVOC_SHORT'}[d['how']], lhs)]
        if k == 'enum':
            return ['QP_CBMC_HAVOC(%s);' % lhs]
        if k == 'bool':
            if d['const']:
                return ['*(_Bool *) &(%s) = (nondet_u8() & 1) != 0;' % lhs]
            return ['QP_CBMC_HAVOC_BOOL(%s);' % lhs]
        if k == 'ptr':
            if d['const']:
                return ['*(void **) &(%s) = qp_cbmc_nondet_pointer();' % lhs]
            return ['QP_CBMC_HAVOC_PTR(%s);' % lhs]
        if k == 'fptr':
            self.warnings.append('%s: a function pointer is NULL (CBMC: any value)' % where)
            if d['const']:
                return ['*(void **) &(%s) = 0;' % lhs]
            return ['%s = 0;' % lhs]
        if k == 'float':
            self.refusals.append('%s: an arbitrary floating-point value (%s): floating point is out of scope'
                                 % (where, qt))
            return []
        if k == 'int128':
            self.refusals.append('%s: an arbitrary 128-bit integer (%s): not supported by CompCert' % (where, qt))
            return []
        if k in ('void', 'func'):
            self.refusals.append('%s: cannot give a value of type %s' % (where, qt))
            return []
        if k == 'union':
            r = self.records[d['rid']]
            self.warnings.append('%s: union %s gets arbitrary bytes' % (where, r['name'] or r['spell'] or '(unnamed)'))
            return ['QP_CBMC_HAVOC_BYTES(%s);' % lhs]
        if k in ('incomplete', 'unknown'):
            self.warnings.append('%s: type %s not understood, arbitrary bytes' % (where, d.get('t', qt)))
            return ['QP_CBMC_HAVOC_BYTES(%s);' % lhs]
        if k == 'struct':
            key = self.key(d['rid'])
            if key:
                if d['rid'] not in self.wanted:
                    self.wanted.append(d['rid'])
                return ['qp_cbmc_havoc_%s((void *) &(%s));' % (key, lhs)]
            return self.fields(lhs, '.', d['rid'], where, depth)
        if k == 'array':
            if d['dim'] == '':
                self.warnings.append('%s: flexible array member not given values' % where)
                return []
            e = self.resolve(d['elem'])
            if e['k'] == 'int' and e['spell'] == 'unsigned char':
                return ['QP_CBMC_HAVOC_BYTES(%s);' % lhs]
            i = 'qp_i%d' % depth
            bound = d['dim'] if re.fullmatch(r'\d+', d['dim']) else 'sizeof (%s) / sizeof ((%s)[0])' % (lhs, lhs)
            body = self.havoc('%s[%s]' % (lhs, i), d['elem'], where, depth + 1)
            if not body:
                return []
            return ['{', '\tsize_t %s;' % i, '\tfor (%s = 0; %s < %s; %s = %s + 1) {' % (i, i, bound, i, i)] + \
                ['\t\t' + l for l in body] + ['\t}', '}']
        self.warnings.append('%s: type %s not understood, arbitrary bytes' % (where, qt))
        return ['QP_CBMC_HAVOC_BYTES(%s);' % lhs]

    def fields(self, base, sep, rid, where, depth):
        r = self.records[rid]
        out = []
        if any(not f and self.resolve(t)['k'] == 'union' for f, t, _ in r['fields']):
            self.warnings.append('%s: an unnamed union member: the whole %s gets arbitrary bytes first'
                                 % (where, r['spell'] or 'struct'))
            out.append('QP_CBMC_HAVOC_BYTES(%s);' % (base if sep == '.' else '*' + base))
        for fname, ft, bf in r['fields']:
            if not fname:
                fd = self.resolve(ft)
                if fd['k'] == 'struct':
                    out += self.fields(base, sep, fd['rid'], where, depth + 1)
                continue
            out += self.havoc('%s%s%s' % (base, sep, fname), ft, '%s.%s' % (where, fname), depth + 1, bf)
        return out

    def functions(self, done):
        """(prototypes, definitions) of the typed havoc and allocation functions of the wanted records, closed
        under nesting; `done`: the keys already generated (for another harness source of the same law)."""
        protos, defs, i = [], [], 0
        while i < len(self.wanted):
            rid = self.wanted[i]
            i += 1
            key, r = self.key(rid), self.records[rid]
            if key in done:
                continue
            done.add(key)
            body = ['%s *qp_p = qp_v;' % r['spell']] + self.fields('qp_p', '->', rid, r['spell'], 0)
            protos += ['void qp_cbmc_havoc_%s(void *qp_v);' % key, 'void *qp_cbmc_malloc_%s(void);' % key]
            defs.append('void qp_cbmc_havoc_%s(void *qp_v)\n{\n%s\n}\n\n'
                        'void *qp_cbmc_malloc_%s(void)\n{\n\tvoid *qp_v = qp_cbmc_malloc(sizeof(%s));\n'
                        '\tif (qp_v != NULL)\n\t\tqp_cbmc_havoc_%s(qp_v);\n\treturn qp_v;\n}'
                        % (key, '\n'.join('\t' + l for l in body), key, r['spell'], key))
        return protos, defs


