(* Comparing malloc's result with NULL is defined, also for malloc(0). *)
Lemma malloc_test_null (t: type) (q: val) (P: mpred):
  0 <= sizeof t ->
  (if eq_dec q nullval then emp else malloc_token Ews t q * data_at_ Ews t q) * P
  |-- denote_tc_test_eq q (Vlong (Int64.repr 0)).
Proof.
  intros Ht. destruct (eq_dec q nullval).
  - subst. simpl. entailer!.
  - destruct (zlt 0 (sizeof t)).
    + sep_apply (data_at__valid_ptr Ews t q); [ auto | lia | ]. entailer!.
    + sep_apply (malloc_token_valid_pointer Ews t q); [ lia | ]. entailer!.
Qed.

(* A byte buffer is its first k bytes followed by the rest. *)
Lemma split_bytes: forall sh bs k q, 0 <= k <= Zlength bs ->
  field_compatible (tarray tuchar (Zlength bs)) [] q ->
  data_at sh (tarray tuchar (Zlength bs)) (A.bytes bs) q =
  (data_at sh (tarray tuchar (Zlength (sublist 0 k bs))) (A.bytes (sublist 0 k bs)) q *
   data_at sh (tarray tuchar (Zlength (sublist k (Zlength bs) bs))) (A.bytes (sublist k (Zlength bs) bs))
     (offset_val k q))%logic.
Proof.
  intros.
  rewrite (split2_data_at_Tarray_tuchar sh (Zlength bs) k) by (unfold A.bytes; rewrite ?Zlength_map; lia).
  rewrite (arr_field_address0 tuchar (Zlength bs) q k) by auto.
  unfold A.bytes. rewrite !sublist_map, !Zlength_sublist by lia.
  replace (k - 0) with k by lia. change (sizeof tuchar * k) with (1 * k). rewrite Z.mul_1_l. reflexivity.
Qed.

Lemma body_main: semax_body (QPvarspecs p) Gmain f_main (_main, main_spec_std p).
Proof.
  start_function.
  sep_apply (create_mem_mgr gv).
  forward_call. Intros n.                        (* n = nondet_size() *)
  forward_call.                                  (* qp_assume(n <= 4096) *)
  assert (Hn: n <= 4096).
  { revert H0. change (Int.signed (Int.repr 4096)) with 4096. unfold Int64.ltu.
    rewrite !Int64.unsigned_repr by rep_lia.
    if_tac; simpl; [ intros X; exfalso; apply X; reflexivity | lia ]. }
  forward_call (tarray tuchar n, gv).            (* buf = malloc(n) *)
  { simpl; rep_lia. }
  Intros q.
  forward_if (PROP (q <> nullval)
              LOCAL (temp _n (Vlong (Int64.repr n)); temp _buf q; gvars gv)
              SEP (mem_mgr gv; malloc_token Ews (tarray tuchar n) q; data_at_ Ews (tarray tuchar n) q; has_ext tt)).
  { apply derives_trans with ((if eq_dec q nullval then emp else
      malloc_token Ews (tarray tuchar n) q * data_at_ Ews (tarray tuchar n) q) * TT)%logic;
      [ cancel | apply malloc_test_null; simpl; rep_lia ]. }
  { forward. Exists (Int.repr 0). entailer!. }
  { forward. rewrite if_false by auto. entailer!. }
  Intros.
  forward_call (q, n, Ews).                      (* nondet_bytes(buf, n) *)
  { rewrite if_false by auto. cancel. }
  Intros bs. rewrite if_false by auto. subst n.
  change (map (fun b => Vint (Int.repr b)) bs) with (A.bytes bs).
  forward_call. Intros k.                        (* k = nondet_size() *)
  forward_call.                                  (* qp_assume(k <= n) *)
  assert (Hk: k <= Zlength bs).
  { revert H4. unfold Int64.ltu. rewrite !Int64.unsigned_repr by rep_lia.
    if_tac; simpl; [ intros X; exfalso; apply X; reflexivity | lia ]. }
  forward_call (1, q, Ews, bs).                  (* whole = adler32(1, buf, n) *)
  assert_PROP (field_compatible (tarray tuchar (Zlength bs)) [] q) by entailer!.
  rewrite (split_bytes Ews bs k q) by (auto; lia). Intros.
  forward_call (1, q, Ews, sublist 0 k bs).      (* first = adler32(1, buf, k) *)
  { entailer!. simpl. rewrite Zlength_sublist by lia. replace (k - 0) with k by lia. reflexivity. }
  { split; [ apply Forall_sublist; auto | rewrite Zlength_sublist by lia; rep_lia ]. }
  forward_call (A.adler 1 (sublist 0 k bs), offset_val k q, Ews, sublist k (Zlength bs) bs).
                                                 (* both = adler32(first, buf + k, n - k) *)
  { entailer!. simpl. rewrite Zlength_sublist by lia. reflexivity. }
  { split; [ apply A.adler_range; rep_lia | ].
    split; [ apply Forall_sublist; auto | rewrite Zlength_sublist by lia; rep_lia ]. }
  forward_call.                                  (* qp_assert(whole == both) *)
  { match goal with E: Int.repr (Z.b2z (Int.eq _ _)) = Int.zero |- _ => revert E end.
    rewrite A.adler_app by rep_lia. rewrite sublist_rejoin by lia. rewrite sublist_same by lia.
    rewrite Int.eq_true. simpl. intro X; discriminate X. }
  assert (M: (data_at Ews (tarray tuchar (Zlength (sublist 0 k bs))) (A.bytes (sublist 0 k bs)) q *
              data_at Ews (tarray tuchar (Zlength (sublist k (Zlength bs) bs))) (A.bytes (sublist k (Zlength bs) bs))
                (offset_val k q))%logic
             |-- data_at Ews (tarray tuchar (Zlength bs)) (A.bytes bs) q)
    by (rewrite <- split_bytes by (auto; lia); auto).
  sep_apply M.
  sep_apply (data_at_data_at_ Ews (tarray tuchar (Zlength bs)) (A.bytes bs) q).
  forward_call (tarray tuchar (Zlength bs), q, gv).   (* free(buf) *)
  { rewrite if_false by auto. cancel. }
  forward.
  Exists (Int.repr 0). entailer!.
Qed.

