#!/usr/bin/env bash
# tools/fuzz/determinism.sh [--workspace DIR] PROJECT: check that `tools/qp import-fuzz` and `tools/qp import-cbmc`
# are pure functions of their inputs.
#
# Every imported law of PROJECT is regenerated twice, from its own provenance line (`command:`), in two
# fresh copies of the project made in different directories (two temporary workspaces), with different
# environments (TZ, LANG, PYTHONHASHSEED, umask, working directory), and the outputs (the laws, the shims, the
# rewritten harness code and the generated env files of CBMC laws, quickproof.conf) are compared byte for byte
# with each other and with the committed files.  Exit status 0 = identical.  The workspace is found as tools/qp finds it: --workspace, else $QP_WORKSPACE, else the nearest
# ancestor of the current directory with projects/.  The project's UPSTREAM must be a URL or an absolute path
# (a relative one would resolve differently in the copies).
#
# The project is only read.  Each copy is a new directory built by tar from the project's real directory (its
# path resolved, symlinks inside dereferenced), WITHOUT the files the importers write: the imported laws, harness/fuzz/,
# harness/cbmc/, the generated env/LAW.c of CBMC laws and the importers' blocks of quickproof.conf.  Nothing is deleted anywhere: the copies start without those files
# instead (copying the project and then deleting the imported laws in the copy would delete the project's own laws
# when projects/PROJECT is a symlink).  Every write goes through `in_tmp`, which refuses a path that does not
# resolve to inside this run's temporary directory.  Hand-written laws next to the imported ones are copied as they
# are and are not compared.
set -euo pipefail
QP=$(cd "$(dirname "$0")/.." && pwd)/qp
WS=${QP_WORKSPACE:-}
if [ "${1:-}" = --workspace ]; then WS=${2:?--workspace DIR}; shift 2; fi
P=${1:?usage: tools/fuzz/determinism.sh [--workspace DIR] PROJECT}
if [ -z "$WS" ]; then
  WS=$(pwd -P)
  while [ ! -d "$WS/projects" ]; do
    [ "$WS" != / ] || { echo "no workspace: pass --workspace DIR or set QP_WORKSPACE" >&2; exit 2; }
    WS=$(dirname "$WS")
  done
fi
[ -d "$WS/projects/$P" ] || { echo "no project $WS/projects/$P" >&2; exit 2; }
SRC=$(cd "$WS/projects/$P" && pwd -P)          # the real directory, also when projects/$P is a symlink
up=$(bash -c 'cd "$(dirname "$1")" && source "$1" > /dev/null && echo "$UPSTREAM"' _ "$SRC/project.conf")
case $up in
  /*|*://*|*@*:*) ;;
  *) echo "determinism.sh: UPSTREAM=$up is a relative path: use a URL or an absolute path" >&2; exit 2 ;;
esac
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
TMP=$(cd "$TMP" && pwd -P)
in_tmp() {   # $1 a path about to be written: it must resolve to inside $TMP
  local d r
  d=$(dirname "$1")
  r=$(cd "$d" 2>/dev/null && pwd -P) || { echo "determinism.sh: refusing $1 (no directory)" >&2; exit 3; }
  case "$r/" in
    "$TMP"/*) ;;
    *) echo "determinism.sh: refusing to write $1: it resolves outside $TMP" >&2; exit 3 ;;
  esac
  [ ! -L "$1" ] || { echo "determinism.sh: refusing to write through the symlink $1" >&2; exit 3; }
}
laws=$(grep -l -e 'qp-import-fuzz provenance' -e 'qp-import-cbmc provenance' "$SRC"/harness/*.c 2>/dev/null \
  | xargs -r -n1 basename | sed 's/\.c$//' | sort)
[ -n "$laws" ] || { echo "no imported law in $SRC" >&2; exit 2; }
# the env files tools/qp import-cbmc generated (a hand-written env/LAW.c is the project's own: copied, not compared)
envs=$(for law in $laws; do f=$SRC/env/$law.c
  if [ -f "$f" ] && [ "$(head -c 400 "$f" | grep -c 'Generated by tools/qp import-cbmc')" != 0 ]; then echo "env/$law.c"; fi
done)
# the files the importers write, relative to a project directory $1: the laws, the shims and harness copies, the
# generated env files, quickproof.conf
outputs() {
  for law in $laws; do echo "harness/$law.c"; done
  (cd "$1" && find harness/fuzz harness/cbmc -type f 2>/dev/null | LC_ALL=C sort)
  for e in $envs; do echo "$e"; done
  echo quickproof.conf
}
excludes=(--exclude=./harness/fuzz --exclude=./harness/cbmc)
for law in $laws; do excludes+=("--exclude=./harness/$law.c"); done
for e in $envs; do excludes+=("--exclude=./$e"); done
run() {   # $1 = label, then env assignments for the run
  local label=$1; shift
  local ws=$TMP/$label
  mkdir -p "$ws/projects/$P"
  (cd "$SRC" && tar -ch "${excludes[@]}" -f - .) | tar -C "$ws/projects/$P" -xf -
  if [ -n "$(find "$ws" -type l)" ]; then echo "determinism.sh: a symlink in the copy $ws" >&2; exit 3; fi
  in_tmp "$ws/projects/$P/quickproof.conf"
  # quickproof.conf without the importers' blocks (the imports below write them again)
  awk '/^# >>> qp import-(fuzz|cbmc)/ {skip = 1} !skip {print} /^# <<< qp import-(fuzz|cbmc)/ {skip = 0}' \
    "$SRC/quickproof.conf" > "$ws/projects/$P/quickproof.conf"
  for law in $laws; do
    [ ! -e "$ws/projects/$P/harness/$law.c" ] || { echo "determinism.sh: $law.c in the copy" >&2; exit 3; }
    cmd=$(sed -n 's/^ \*   command:        tools\/qp //p' "$SRC/harness/$law.c")
    # the command line as the importer wrote it (its arguments shell-quoted where needed)
    eval "args=($cmd)"
    (cd /; env "$@" "$QP" --workspace "$ws" "${args[@]}" --no-check > /dev/null)
  done
  # shellcheck disable=SC2046
  (cd "$ws/projects/$P" && sha256sum $(outputs "$ws/projects/$P")) > "$TMP/$label.sha"
}
run a TZ=UTC LANG=C PYTHONHASHSEED=1
(umask 077; run b TZ=Asia/Tokyo LANG=en_US.UTF-8 PYTHONHASHSEED=4242)
# shellcheck disable=SC2046
(cd "$SRC" && sha256sum $(outputs "$SRC")) > "$TMP/committed.sha"
status=0
for x in b committed; do
  if diff -u "$TMP/a.sha" "$TMP/$x.sha" > "$TMP/diff.$x"; then
    echo "run a = $x: identical ($(wc -l < "$TMP/a.sha") files)"
  else
    echo "run a != $x:"; cat "$TMP/diff.$x"; status=1
  fi
done
cat "$TMP/a.sha"
exit $status
