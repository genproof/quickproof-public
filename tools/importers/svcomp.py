"""svcomp.py: `tools/qp import-svcomp`, laws from SV-COMP verification tasks (docs/SVCOMP.md).

    qp import-svcomp NAME TASK.yml [--property P] [--law L] [--malloc may-fail|never-fails] [--no-check] [--contract]
    qp import-svcomp NAME --verdicts [LAW..] [-n RUNS] [--timeout S] [--interp N] [--interp-timeout S] [--out FILE]

An SV-COMP task (a task-definition file TASK.yml, format 2.x, of the project's upstream, e.g. sv-benchmarks at a
commit) becomes a law: the task's C file, copied with at most two textual normalisations, compiled as is after a
header-free shim (tools/svcomp/svcomp_env.h) that gives __VERIFIER_*, reach_error, abort and exit their SV-COMP
meaning in terms of quickproof.h; its `main` renamed and called by the law's `main`.  The task's expected verdict
is recorded: a law whose task is expected to be false goes to BROKEN in project.conf.  `--verdicts` runs the
imported laws natively and under CompCert's interpreter and compares what they find with the expected verdicts
(projects/NAME/SVCOMP.md).

The translation is a pure function of the task files at the pinned commit, the options, the shim, the libc and
VERSION.  It is loaded by tools/qp, which passes itself as the module `qp` (its helpers: upstream files, trees,
native builds, clightgen, the Clight audit).
"""
