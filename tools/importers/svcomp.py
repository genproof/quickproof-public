VERSION = 1                      # bump when the generated text, the shim or the libc changes
MARK = 'qp-import-svcomp provenance'
SHIM = 'svcomp_env.h'            # tools/svcomp/SHIM -> projects/NAME/harness/svcomp/SHIM
LIBC = 'svcomp_libc.h'
CONF_BEGIN = ('# >>> qp import-svcomp: one unit per imported law (generated by tools/qp import-svcomp, importer '
              'version %d; do not edit)' % VERSION)
CONF_END = '# <<< qp import-svcomp'
BROKEN_BEGIN = ('# >>> qp import-svcomp: the imported laws whose task is expected to be false (generated by '
                'tools/qp import-svcomp; do not edit)')

# The SV-COMP vocabulary the shim defines (unless the task defines it itself), and the refused one.
NONDET = {'char', 'uchar', 'short', 'ushort', 'int', 'uint', 'unsigned', 'u32', 'long', 'ulong', 'longlong',
          'ulonglong', 'size_t', 'loff_t', 'sector_t', 'bool', 'memory'}
NONDET_REFUSED = {'float': 'a floating-point value', 'double': 'a floating-point value',
                  'pointer': 'a pointer value', 'pchar': 'a pointer value', 'pthread_t': 'a thread',
                  'int128': 'a 128-bit integer', 'uint128': 'a 128-bit integer'}
SHIM_DEFINABLE = ['__assert_fail', '__VERIFIER_assume', '__VERIFIER_error', '__VERIFIER_nondet_memory'] + \
    ['__VERIFIER_nondet_' + t for t in sorted(NONDET - {'memory'})]
LIBC_FUNCS = ['memcpy', 'memmove', 'memset', 'memcmp', 'memchr', 'strlen', 'strnlen', 'strcmp', 'strncmp', 'strchr',
              'strrchr', 'strcpy', 'strncpy', 'strcat', 'strncat', 'strspn', 'strcspn', 'strdup', 'abs', 'labs']
# input functions (Juliet's sources of data): no model in version 1
INPUT_FUNCS = ['fgets', 'fgetc', 'getc', 'getchar', 'fscanf', 'scanf', 'sscanf', 'fread', 'read', 'recv', 'recvfrom',
               'rand', 'random', 'socket', 'getenv']

# The properties: what the theorem of a law implies of each (docs/SVCOMP.md).
SUPPORTED = ['unreach-call', 'valid-memsafety', 'no-overflow', 'valid-memcleanup']
MEANING = {
    'unreach-call': 'no execution calls reach_error() (every gp_assert holds)',
    'valid-memsafety': 'no execution dereferences an invalid pointer or frees an invalid pointer (valid-deref, '
                       'valid-free; valid-memtrack, that memory stays reachable, is not covered)',
    'no-overflow': 'no execution overflows a signed integer in + - * / or unary - (VST\'s type checks; shifts are '
                   'not checked)',
    'valid-memcleanup': 'every block that malloc or calloc returns is freed when the program ends, by returning from '
                        'main or by abort() or exit()',
}


def die(msg):
    raise SystemExit('qp: import-svcomp: ' + msg)


# ---- the task-definition file: the subset of YAML that SV-COMP uses ------------------------------------------

def _strip_comment(line):
    q = None
    for i, ch in enumerate(line):
        if q:
            if ch == q:
                q = None
        elif ch in '\'"':
            q = ch
        elif ch == '#' and (i == 0 or line[i - 1] in ' \t'):
            return line[:i]
    return line


def _scalar(s):
    s = s.strip()
    if s.startswith('[') and s.endswith(']'):
        return [_scalar(x) for x in s[1:-1].split(',') if x.strip()]
    if len(s) >= 2 and s[0] == s[-1] == "'":
        return s[1:-1].replace("''", "'")
    if len(s) >= 2 and s[0] == s[-1] == '"':
        return s[1:-1].replace('\\"', '"').replace('\\\\', '\\')
    if s[:1] in ('|', '>', '&', '*', '!', '{'):
        die('unsupported YAML in the task-definition file: %s' % s[:40])
    low = s.lower()
    if low in ('true', 'false'):
        return low == 'true'
    return s


def _block(lines, i, ind):
    if lines[i][1] == '-' or lines[i][1].startswith('- '):
        return _seq(lines, i, ind)
    return _map(lines, i, ind)


def _seq(lines, i, ind):
    out = []
    while i < len(lines) and lines[i][0] == ind and (lines[i][1] == '-' or lines[i][1].startswith('- ')):
        rest = lines[i][1][1:].lstrip(' ')
        if not rest:
            if i + 1 < len(lines) and lines[i + 1][0] > ind:
                v, i = _block(lines, i + 1, lines[i + 1][0])
            else:
                v, i = None, i + 1
        elif re.match(r'^([^\'"\s][^:]*|\'[^\']*\'|"[^"]*"):(\s|$)', rest):
            lines[i] = (ind + len(lines[i][1]) - len(rest), rest)       # a mapping that starts on this line
            v, i = _map(lines, i, lines[i][0])
        else:
            v, i = _scalar(rest), i + 1
        out.append(v)
    return out, i


def _map(lines, i, ind):
    out = {}
    while i < len(lines) and lines[i][0] == ind and not (lines[i][1] == '-' or lines[i][1].startswith('- ')):
        m = re.match(r'^([^\'"\s][^:]*|\'[^\']*\'|"[^"]*"):(?:\s+(.*))?$', lines[i][1])
        if not m:
            die('unsupported YAML in the task-definition file: %s' % lines[i][1][:60])
        key, rest = _scalar(m.group(1)), (m.group(2) or '').strip()
        i += 1
        if rest:
            out[key] = _scalar(rest)
        elif i < len(lines) and (lines[i][0] > ind or (lines[i][0] == ind and lines[i][1].startswith('- '))):
            out[key], i = _block(lines, i, lines[i][0])
        else:
            out[key] = None
    if i < len(lines) and lines[i][0] > ind:
        die('bad indentation in the task-definition file: %s' % lines[i][1][:60])
    return out, i


def parse_task(text):
    """The task-definition file as nested dicts and lists (block mappings and sequences, flow sequences of
    scalars, quoted and plain scalars, comments; nothing else)."""
    lines = []
    for raw in text.splitlines():
        if '\t' in raw[:len(raw) - len(raw.lstrip())]:
            die('a tab in the indentation of the task-definition file')
        s = _strip_comment(raw).rstrip()
        if s.strip() in ('', '---'):
            continue
        lines.append((len(s) - len(s.lstrip(' ')), s.lstrip(' ')))
    if not lines:
        die('empty task-definition file')
    v, i = _block(lines, 0, lines[0][0])
    if i != len(lines) or not isinstance(v, dict):
        die('the task-definition file is not a mapping')
    return v


def property_kind(prp):
    """The property a .prp file states: (kind, details), kind in SUPPORTED, 'termination', or None."""
    checks = re.findall(r'CHECK\s*\(\s*init\s*\(\s*main\s*\(\s*\)\s*\)\s*,\s*LTL\s*\((.*)\)\s*\)', prp)
    checks = [' '.join(c.split()) for c in checks]
    if not checks:
        return None, ''
    m = re.fullmatch(r'G ! call\((\w+)\(\)\)', checks[0])
    if len(checks) == 1 and m:
        return 'unreach-call', m.group(1)
    if sorted(checks) == ['G valid-deref', 'G valid-free', 'G valid-memtrack']:
        return 'valid-memsafety', ''
    if checks == ['G valid-memcleanup']:
        return 'valid-memcleanup', ''
    if checks == ['G ! overflow']:
        return 'no-overflow', ''
    if checks == ['F end']:
        return 'termination', ''
    return None, '; '.join(checks)


# ---- reading the task's C text ---------------------------------------------------------------------------------

ASSERT_EXPANSION = re.compile(
    r'\(\(void\) sizeof \(\((?P<c1>[^;]*?)\) \? 1 : 0\), __extension__ \(\{ if \((?P<c2>[^;]*?)\) ; '
    r'else __assert_fail \((?P<args>[^;]*?)\); \}\)\)')


ASM_LABEL = re.compile(r'(?<=[)\w])(\s*)\b(?:__asm__|__asm)(\s*\((?:\s*"[^"\n]*")+\s*\))')
REACH_ERROR_DEF = re.compile(r'(?m)^[\w \t*]*?\breach_error\s*\(\s*(?:void)?\s*\)\s*\{')


def normalise(text):
    """The edits of the task text, each counted: glibc's assert() expansion, a GNU statement expression that
    CompCert does not accept, rewritten to the equivalent conditional call of __assert_fail; __PRETTY_FUNCTION__
    (GNU) as __func__; an asm label of a declaration (`__asm__ ("" "__isoc99_fscanf")`, which CompCert does not
    accept) kept for gcc only (QP_SVCOMP_ASM_LABEL); __attribute__((__cdecl__)) (Cygwin's headers), which has no
    effect on x86-64 and which CompCert does not parse inside declarators, removed; and a failing check at the start of reach_error's body, so
    that every call of it fails, whatever its body does.  Comments and string literals are left alone.  Returns
    (text, [edit descriptions], reach_error defined)."""
    edits = []

    def subn(pattern, repl, s):
        c = strip_c(s)
        out, last, n = [], 0, 0
        for m in pattern.finditer(s):
            if c[m.start():m.end()].strip() == '' or c[m.end() - 1] != s[m.end() - 1]:
                continue                                   # in a comment or a literal
            out.append(s[last:m.start()])
            out.append(repl(m))
            last, n = m.end(), n + 1
        out.append(s[last:])
        return ''.join(out), n
    text, n = subn(ASSERT_EXPANSION, lambda m: '((%s) ? (void) 0 : __assert_fail (%s))' % (m.group('c2'), m.group('args')),
                   text)
    if n:
        edits.append('%d glibc assert expansion%s rewritten without a statement expression' % (n, 's' if n > 1 else ''))
    text, k = subn(re.compile(r'(?:__extension__\s+)?\b__PRETTY_FUNCTION__\b'), lambda m: '__func__', text)
    if k:
        edits.append('%d __PRETTY_FUNCTION__ written __func__' % k)
    text, a = subn(ASM_LABEL, lambda m: m.group(1) + 'QP_SVCOMP_ASM_LABEL' + m.group(2), text)
    if a:
        edits.append('%d asm label%s of declarations kept for gcc only' % (a, 's' if a > 1 else ''))
    text, d = subn(re.compile(r'__attribute__\s*\(\(\s*__cdecl__\s*\)\)\s?'), lambda m: '', text)
    if d:
        edits.append('%d __attribute__((__cdecl__)) removed (no effect on x86-64; CompCert does not parse it inside '
                     'declarators)' % d)
    text, r = subn(REACH_ERROR_DEF, lambda m: m.group(0) + ' qp_svcomp_reach_error();', text)
    if r:
        edits.append('a failing check at the start of reach_error')
    return text, edits, r > 0


def definition(code, name):
    """The body of the function `name` defined in code (comments and literals blanked), or None.  A definition
    starts its line with the return type and qualifiers only, so calls (`if (strlen(s)) {`) do not match."""
    m = re.search(r'(?m)^[\w \t*]*?\b%s\s*\(((?:[^()]|\([^()]*\))*)\)\s*\{' % re.escape(name), code)
    if not m:
        return None
    depth, i = 0, m.end() - 1
    while i < len(code):
        if code[i] == '{':
            depth += 1
        elif code[i] == '}':
            depth -= 1
            if depth == 0:
                return code[m.end():i]
        i += 1
    return code[m.end():]


def called(code, name):
    """name is called in code: an occurrence `name (` that is not a declaration (not preceded by a type name or
    a `*`, as in `extern char *fgets (` or `int fscanf (`)."""
    for m in re.finditer(r'\b%s\s*\(' % re.escape(name), code):
        before = code[max(0, m.start() - 300):m.start()].rstrip()
        while True:                              # `char * __attribute__((__cdecl__)) getenv (`: a declaration
            a = re.search(r'__attribute__\s*\(\((?:[^()]|\((?:[^()]|\([^()]*\))*\))*\)\)$', before)
            if not a:
                break
            before = before[:a.start()].rstrip()
        if before.endswith('*'):                 # `char *fgets (`: a declaration; `= *f(`: a call
            before = before.rstrip('* \t\n')
            if re.search(r'\w$', before):
                continue
        prev = re.search(r'(\w+)$', before)
        if prev and prev.group(1) not in ('return', 'else', 'do', 'case', 'sizeof'):
            continue                             # a type before the name: a declaration
        return True
    return False


def analyse(text, prop_kind, prop_func):
    """Refusals and notes for the task text, and the functions the task defines itself (left to it)."""
    code = strip_c(text)
    refused, notes = [], []
    for name in sorted(set(re.findall(r'\b__VERIFIER_(\w+)', code))):
        full = '__VERIFIER_' + name
        own = definition(code, full) is not None
        if name.startswith('nondet_'):
            t = name[len('nondet_'):]
            if t in NONDET_REFUSED and not own:
                refused.append('%s: %s (not supported)' % (full, NONDET_REFUSED[t]))
            elif t not in NONDET and not own:
                refused.append('%s: not an SV-COMP nondet function this importer knows' % full)
        elif name.startswith('atomic'):
            refused.append('%s: atomic sections (threads)' % full)
        elif name not in ('assume', 'error') and not own:
            refused.append('%s: not an SV-COMP function this importer knows' % full)
    if called(code, 'pthread_create') or called(code, 'thrd_create'):
        refused.append('uses threads')
    if any(called(code, f) for f in ('setjmp', '_setjmp', 'sigsetjmp', '__sigsetjmp', 'longjmp', '_longjmp', 'siglongjmp')):
        refused.append('uses setjmp/longjmp')
    checks = [
        (r'\b(?:__asm__|__asm|asm)\s*(?:__volatile__|volatile|goto)?\s*\((?:[^();]|\([^()]*\))*:', 'inline assembly'),
        (r'\b__int128\b|\b__uint128_t\b|\b__int128_t\b', '__int128'),
    ]
    for pat, why in checks:
        if re.search(pat, code):
            refused.append('uses %s' % why)
    main = definition(code, 'main')
    if main is None:
        refused.append('no definition of main')
    else:
        m = re.search(r'(?m)^[\w \t*]*?\bmain\s*\(((?:[^()]|\([^()]*\))*)\)\s*\{', code)
        params = ' '.join(m.group(1).split())
        if params not in ('', 'void'):
            refused.append('main takes arguments (%s)' % params)
    inputs = [f for f in INPUT_FUNCS if called(code, f)]
    if inputs:
        refused.append('reads input (%s): no input model in this version' % ', '.join(inputs))
    add_reach_error = False
    if prop_kind == 'unreach-call':
        if prop_func not in ('reach_error', '__VERIFIER_error'):
            refused.append('the property is about calls of %s (expected reach_error)' % prop_func)
        elif prop_func == 'reach_error' and definition(code, 'reach_error') is None and called(code, 'reach_error'):
            add_reach_error = True
    if re.search(r'\bgoto\b', code):
        notes.append('uses goto: VST has no rule for it (the cone check reports it; an idiom patch can remove it)')
    if re.search(r'(?m)(?:^|[;{}])\s*(?:(?:static|const|volatile|register|long)\s+)*(float|double)\s+\**\s*[A-Za-z_]\w*'
                 r'\s*[=;\[,]|\(\s*(float|double)\s*\)', code):
        notes.append('uses floating point (no nondet floating-point value; VST and the audit see the rest)')
    own = [f for f in SHIM_DEFINABLE + LIBC_FUNCS if definition(code, f) is not None]
    return refused, notes, own, add_reach_error


def strip_c(s):
    """C text with comments and the contents of string and character literals blanked."""
    s = re.sub(r'/\*.*?\*/', lambda m: re.sub(r'[^\n]', ' ', m.group(0)), s, flags=re.S)
    s = re.sub(r'//[^\n]*', lambda m: ' ' * len(m.group(0)), s)
    s = re.sub(r'"(\\.|[^"\\\n])*"', lambda m: '"' + ' ' * (len(m.group(0)) - 2) + '"', s)
    s = re.sub(r"'(\\.|[^'\\\n])'", lambda m: "'" + ' ' * (len(m.group(0)) - 2) + "'", s)
    return s


# ---- the import ------------------------------------------------------------------------------------------------

def import_parser():
    a = argparse.ArgumentParser(prog='qp import-svcomp', add_help=False)
    a.add_argument('task')
    a.add_argument('--law')
    a.add_argument('--property')
    a.add_argument('--malloc', choices=['may-fail', 'never-fails'], default='may-fail')
    a.add_argument('--no-check', action='store_true')
    a.add_argument('--contract', action='store_true')
    return a


def law_name_of(task):
    stem = re.sub(r'\.ya?ml$', '', os.path.basename(task))
    stem = re.sub(r'[^A-Za-z0-9_]', '_', stem)
    if not re.match(r'[A-Za-z_]', stem):
        stem = 'sv_' + stem
    return stem


def rel_path(base_dir, f):
    p = os.path.normpath(os.path.join(base_dir, f))
    if p.startswith('..') or os.path.isabs(p):
        die('%s is outside the upstream tree' % f)
    return p


def verdict_text(v):
    return {True: 'true', False: 'false', None: 'none'}.get(v, str(v))


def law_verdict(props, chosen, leaks):
    """The expected verdict of the law from the task's expected verdicts: false when a property the theorem
    implies is expected false; true when the chosen property is expected true and none is false; else unknown."""
    false_because = []
    for name, (kind, _, verdict, sub) in props.items():
        if verdict is not False:
            continue
        if kind in ('unreach-call', 'no-overflow') or (kind == 'valid-memcleanup' and leaks):
            false_because.append(name)
        elif kind == 'valid-memsafety' and sub in ('valid-deref', 'valid-free'):
            false_because.append('%s (%s)' % (name, sub))
    if false_because:
        return 'false', false_because
    if props[chosen][2] is True:
        return 'true', []
    return 'unknown', []


def claim_text(task, prop, verdict, law_v, malloc, leaks):
    t = ['Law imported from the SV-COMP task `%s` (property %s, expected verdict %s) by tools/qp import-svcomp. '
         'For every value of every __VERIFIER_nondet_* call and every execution under __VERIFIER_assume, with abort() '
         'and exit() ending the execution without error%s: %s; and, as for every QuickProof law, no execution has '
         'undefined behaviour in CompCert C (so also no invalid dereference or free, and no signed overflow in + - * '
         '/). Assumed beyond SV-COMP: %s. Not covered: termination%s.'
         % (task, prop, verdict_text(verdict),
            ', malloc and calloc never returning NULL' if malloc == 'never-fails' else '',
            MEANING[prop],
            'allocations succeed (--malloc never-fails)' if malloc == 'never-fails' else
            'nothing (malloc may return NULL, alloca does not fail)',
            ', valid-memtrack' if not leaks else '')]
    if law_v == 'false':
        t.append(' The task is expected to violate a property the theorem implies, so this law is false: a proof '
                 'must fail with a counterexample (the law is in BROKEN).')
    return ''.join(t)


def generate(qp, p, argv):
    """The files of an imported law: {path relative to projects/NAME: bytes}, its name, and the report."""
    a = import_parser().parse_args(argv)
    task = os.path.normpath(a.task)
    tbytes = qp.upstream_file(p, task)
    y = parse_task(tbytes.decode('utf-8', 'replace'))
    refused, notes = [], []
    opts = y.get('options') or {}
    if not isinstance(opts, dict):
        die('%s: options is not a mapping' % task)
    if str(opts.get('language', 'C')) != 'C':
        refused.append('language %s (C only)' % opts.get('language'))
    if opts.get('data_model') != 'LP64':
        refused.append('data model %s (QuickProof is x86-64 LP64 only)' % (opts.get('data_model') or 'not given, ILP32'))
    files = y.get('input_files')
    files = files if isinstance(files, list) else [files] if files else []
    if len(files) != 1:
        die('%s: %d input files (one is supported)' % (task, len(files)))
    tdir = os.path.dirname(task)
    src = rel_path(tdir, files[0])
    props = {}          # name -> (kind, details, expected verdict, subproperty), in the order of the file
    prp_files = {}
    for e in y.get('properties') or []:
        if not isinstance(e, dict) or not e.get('property_file'):
            continue
        pf = rel_path(tdir, e['property_file'])
        name = re.sub(r'\.prp$', '', os.path.basename(pf))
        pb = qp.upstream_file(p, pf)
        kind, details = property_kind(pb.decode('utf-8', 'replace'))
        props[name] = (kind, details, e.get('expected_verdict'), e.get('subproperty'))
        prp_files[name] = (pf, pb)
    usable = [n for n in props if props[n][0] in SUPPORTED]
    if a.property:
        if a.property not in props:
            die('%s has no property %s (it has: %s)' % (task, a.property, ', '.join(props) or 'none'))
        if props[a.property][0] not in SUPPORTED:
            die('property %s (%s) is not supported: a law can imply %s' % (a.property, props[a.property][0] or
                props[a.property][1] or 'unknown', ', '.join(SUPPORTED)))
        prop = a.property
    elif usable:
        prop = usable[0]                      # the first supported property of the task file
    else:
        die('%s: no supported property (it has: %s; a law can imply %s)' % (task, ', '.join(props) or 'none',
                                                                          ', '.join(SUPPORTED)))
    kind = props[prop][0]
    leaks = kind == 'valid-memcleanup'
    law = a.law or law_name_of(task)
    if not re.fullmatch(r'[A-Za-z_]\w*', law):
        die('law name %s is not a C identifier' % law)
    ibytes = qp.upstream_file(p, src)
    text = ibytes.decode('latin-1')
    r2, n2, own, add_reach_error = analyse(text, kind, props[prop][1])
    refused += r2
    notes += n2
    if refused:
        die('%s is not imported:\n  %s' % (task, '\n  '.join(refused)))
    norm, edits, _ = normalise(text)
    copy = norm.encode('latin-1')
    ext = '.i' if src.endswith('.i') else '.c'
    copy_rel = 'svcomp/%s%s' % (law, ext)
    law_v, false_because = law_verdict(props, prop, leaks)

    def stamped(name):
        t = open(os.path.join(qp.TOOLS, 'svcomp', name), 'rb').read()
        return ('/* Generated by tools/qp import-svcomp (importer version %d): a copy of tools/svcomp/%s\n'
                ' * (sha256 %s); do not edit, any import into this project rewrites it. */\n'
                % (VERSION, name, qp.sha256(t))).encode() + t
    shim, libc = stamped(SHIM), stamped(LIBC)
    command = ' '.join(['tools/qp', 'import-svcomp', p.name, task, '--law', law, '--property', prop, '--malloc', a.malloc])
    verdicts = '; '.join('%s %s%s' % (n, verdict_text(v[2]), ' (%s)' % v[3] if v[3] else '')
                         for n, v in props.items() if v[2] is not None) or 'none'
    L = [qp.comment_block(claim_text(task, prop, props[prop][2], law_v, a.malloc, leaks)), '',
         '/* %s (generated; do not edit; regenerate with the command below)' % MARK,
         ' *   importer:       tools/qp import-svcomp, version %d' % VERSION,
         ' *   command:        %s' % command,
         ' *   upstream:       %s' % p.upstream_conf,
         ' *   commit:         %s' % p.commit,
         ' *   task:           %s sha256 %s' % (task, qp.sha256(tbytes)),
         ' *   input:          %s sha256 %s' % (src, qp.sha256(ibytes)),
         ' *   property:       %s sha256 %s' % (prp_files[prop][0], qp.sha256(prp_files[prop][1])),
         ' *   verdicts:       %s' % verdicts,
         ' *   law:            expected %s%s' % (law_v, ' (%s), in BROKEN' % ', '.join(false_because) if false_because else ''),
         ' *   copy:           harness/%s sha256 %s (%s)' % (copy_rel, qp.sha256(copy), '; '.join(edits) or 'no edit'),
         ' *   shim:           harness/svcomp/%s sha256 %s' % (SHIM, qp.sha256(shim)),
         ' *   libc:           harness/svcomp/%s sha256 %s' % (LIBC, qp.sha256(libc)),
         ' *   options:        law=%s property=%s malloc=%s' % (law, prop, a.malloc),
         ' *   task-defined:   %s' % (', '.join(own) or 'none'),
         ' * The sha256 of the task, input and property files are of the upstream files at the commit. */',
         '#define QP_SVCOMP_MALLOC_NEVER_FAILS %d' % (1 if a.malloc == 'never-fails' else 0),
         '#define QP_SVCOMP_LEAKS %d' % (1 if leaks else 0)]
    L += ['#define QP_SVCOMP_OWN_%s 1' % f for f in own if f in SHIM_DEFINABLE]
    L += ['#include "svcomp/%s"' % SHIM, '',
          '/* The task, compiled as is: its main is renamed, the law\'s main calls it. */',
          '#pragma push_macro("main")', '#undef main', '#define main qp_svcomp_task_main',
          '#include "%s"' % copy_rel, '#pragma pop_macro("main")', '']
    if add_reach_error:
        L += ['/* The task calls reach_error() without defining it. */',
              'void reach_error(void)', '{', '\tqp_assert(0);', '}', '']
    L.append('/* The C library functions in plain C (for the theorem and the interpreter; native runs use the system\'s). */')
    L += ['#define QP_SVCOMP_OWN_%s 1' % f for f in own if f in LIBC_FUNCS]
    L += ['#include "svcomp/%s"' % LIBC, '',
          'int main(void)', '{', '\tqp_svcomp_task_main();']
    if leaks:
        L.append('\tqp_assert(qp_svcomp_live == 0);        /* valid-memcleanup: every block is freed */')
    L += ['\tqp_assert(1);        /* the end is reached: a marker for the native runs\' tally (trivially true) */',
          '\treturn 0;', '}', '']
    out = {'harness/%s.c' % law: '\n'.join(L).encode(), 'harness/' + copy_rel: copy,
           'harness/svcomp/' + SHIM: shim, 'harness/svcomp/' + LIBC: libc}
    report = dict(law=law, task=task, property=prop, expected=props[prop][2], law_verdict=law_v, notes=notes,
                  edits=edits, own=own, no_check=a.no_check, contract=a.contract)
    return law, out, report


def imported_laws(pdir):
    """{law: its provenance fields} of the laws of tools/qp import-svcomp in projects/NAME/harness."""
    out = {}
    hdir = os.path.join(pdir, 'harness')
    for f in sorted(os.listdir(hdir)) if os.path.isdir(hdir) else []:
        if not f.endswith('.c'):
            continue
        text = open(os.path.join(hdir, f), errors='replace').read(8192)
        if MARK in text:
            block = text.split(MARK, 1)[1].split('*/', 1)[0]
            out[f[:-2]] = dict(re.findall(r'^ \*   ([\w-]+):\s+(.*)$', block, re.M))
    return out


def conf_block(text, laws):
    """quickproof.conf with the managed block of imported law units set to `laws`."""
    text = re.sub(r'\n?# >>> qp import-svcomp:[^\n]*\n.*?' + re.escape(CONF_END) + r'\n', '\n', text, flags=re.S)
    text = text.rstrip('\n') + '\n'
    if laws:
        text += '\n%s\nUNITS+=(\n%s)\n%s\n' % (CONF_BEGIN, ''.join('  "harness/%s.c=src/harness/%s"\n' % (l, l)
                                                                   for l in laws), CONF_END)
    return text


def broken_block(text, laws):
    """project.conf with the managed block that adds `laws` to BROKEN."""
    text = re.sub(r'\n?# >>> qp import-svcomp:[^\n]*\n.*?' + re.escape(CONF_END) + r'\n', '\n', text, flags=re.S)
    text = text.rstrip('\n') + '\n'
    if laws:
        text += '\n%s\nBROKEN="$BROKEN %s"\n%s\n' % (BROKEN_BEGIN, ' '.join(laws), CONF_END)
    return text


def write(qp, path, data):
    old = open(path, 'rb').read() if os.path.exists(path) else None
    if old != data:
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, 'wb').write(data)
    print('%s %s' % ('unchanged' if old == data else 'wrote', os.path.relpath(path, qp.WORKSPACE)))


def import_task(qp, p, argv):
    law, files, rep = generate(qp, p, argv)
    dst = os.path.join(p.dir, 'harness', law + '.c')
    if os.path.exists(dst) and MARK.encode() not in open(dst, 'rb').read(8192):
        die('%s exists and is not a law of tools/qp import-svcomp; choose another --law' % dst)
    for rel, data in sorted(files.items()):
        write(qp, os.path.join(p.dir, rel), data)
    laws = imported_laws(p.dir)
    for path, new in ((os.path.join(p.dir, qp.CONF), lambda t: conf_block(t, sorted(laws))),
                      (os.path.join(p.dir, 'project.conf'),
                       lambda t: broken_block(t, sorted(l for l, f in laws.items() if f.get('law', '').startswith('expected false'))))):
        text = open(path).read()
        if new(text) != text:
            open(path, 'w').write(new(text))
            print('updated %s' % os.path.relpath(path, qp.WORKSPACE))
    print('%s: property %s, task expected %s, law expected %s%s' % (
        law, rep['property'], verdict_text(rep['expected']), rep['law_verdict'],
        ''.join('\n  note: ' + n for n in rep['notes'])))
    units = qp.source(os.path.join(p.dir, qp.CONF), ['UNITS'], os.path.realpath(qp.framework_dir(p.framework)))['UNITS']
    others = [u.split('=', 1)[0] for u in units if not u.split('=', 1)[0].startswith('harness/')]
    if others:
        print('warning: quickproof.conf lists library units (%s): the law needs none (it carries its own header-free '
              'C library, and malloc and free are the environment\'s), and tools/interp.sh puts every unit in one '
              'translation unit with the task, where their system headers can conflict with a preprocessed task\'s '
              'own copies of them (docs/SVCOMP.md)' % ', '.join(os.path.basename(u) for u in others))
    if rep['no_check']:
        return
    print('== the law\'s program (clightgen: externals, undefined globals, VST blockers in the cone)')
    out = cone(qp, p, law)
    print('\n'.join(out) if out else 'ok: only the framework environment is external, no VST blocker in the cone')
    if rep['contract']:
        d = os.path.join(qp.CACHE, 'svcomp-contract', '%s.%d' % (p.name, os.getpid()))
        shutil.rmtree(d, ignore_errors=True)
        qp.assemble(p, d)
        qp.sh('coq_makefile -f _CoqProject -o CoqMakefile', cwd=d, coq=True, capture=True)
        r = qp.sh(['make', '-f', 'CoqMakefile', '-j2', 'src/contracts/%s.vo' % law], cwd=d, coq=True, check=False,
                  capture=True)
        print('== contract src/contracts/%s.v: %s' % (law, 'builds' if r.returncode == 0 else 'FAILED\n' +
                                                      (r.stdout or '')[-2500:]))
        shutil.rmtree(d, ignore_errors=True)


# ---- checks: a tree of the laws alone, the cone, the expected verdicts -----------------------------------------

def law_tree(qp, p, laws):
    """A tree for the laws of tools/qp import-svcomp: they need nothing from upstream, so it holds only the
    project's harness/ (and env.c, env/), quickproof/ (the framework) and a quickproof.conf with the framework's
    units of the project's configuration and the laws' units.  Removed at exit."""
    import atexit
    d = tempfile.mkdtemp(prefix='qp-svcomp.')
    atexit.register(shutil.rmtree, d, True)
    fw = os.path.realpath(qp.framework_dir(p.framework))
    os.symlink(fw, os.path.join(d, qp.FW))
    for f in ('harness', 'env', 'env.c'):
        s = os.path.join(p.dir, f)
        if os.path.isdir(s):
            shutil.copytree(s, os.path.join(d, f))
        elif os.path.exists(s):
            shutil.copy(s, d)
    v = qp.source(os.path.join(p.dir, qp.CONF), ['INC', 'DEFS', 'UNITS'], fw)
    q = lambda xs: ' '.join("'%s'" % x.replace("'", "'\\''") for x in xs)
    units = [u for u in v['UNITS'] if os.path.realpath(os.path.join(p.dir, u.split('=', 1)[0])).startswith(fw + '/')]
    units += ['harness/%s.c=src/harness/%s' % (l, l) for l in laws]
    open(os.path.join(d, qp.CONF), 'w').write('INC=(%s)\nDEFS=(%s)\nUNITS=(%s)\n' % (q(v['INC']), q(v['DEFS']), q(units)))
    return d


def cone(qp, p, law):
    """Translate the law's program with clightgen (tools/clight.sh) and list what it needs outside itself and what
    VST cannot take in its cone (as tools/qp import-fuzz does)."""
    tree = law_tree(qp, p, [law])
    r = qp.sh([qp.FW + '/tools/clight.sh', qp.CONF], cwd=tree, coq=True, check=False, capture=True)
    if r.returncode:
        return ['clightgen failed:'] + [l for l in (r.stdout or '').splitlines() if 'error' in l.lower()][:12]
    outs = [u.split('=', 1)[1] for u in qp.source(os.path.join(tree, qp.CONF), ['UNITS'])['UNITS']]
    internal, external, gundef, gdef = set(), set(), set(), set()
    for o in outs:
        c = open(os.path.join(tree, o, 'code.v'), errors='replace').read()
        internal |= set(re.findall(r'^Definition f_(\w+) := \{\|', c, re.M))
        external |= set(re.findall(r'EF_external "(\w+)"', c))
        for name, init in re.findall(r'^Definition v_(\w+) := \{\|\n\s*gvar_info := [^\n]*\n\s*gvar_init := (\S+)', c, re.M):
            (gundef if init.startswith('nil') else gdef).add(name)
    missing = sorted(x for x in external - internal - qp.ENV_EXTERNALS if not x.startswith('__builtin_'))
    undef = sorted(gundef - gdef)
    out = ['VST blocker: ' + l for l in qp.clight_blockers(tree, [law])
           if 'external outside the framework environment' not in l]
    if missing:
        out.append('external functions outside the framework environment (no specification in the theorem): '
                   + ', '.join(missing))
    if undef:
        out.append('global variables declared but not defined: ' + ', '.join(undef))
    return out


def native_failure(out):
    """The kind of a failing native run, from its output."""
    if re.search(r'#\d+ 0x[0-9a-f]+ in gp_assert ', out):
        return 'a check failed (reach_error, or an assertion of the law)'
    m = re.search(r'ERROR: (AddressSanitizer|LeakSanitizer): ([^\n]*)', out)
    if m:
        return '%s %s' % (m.group(1), re.split(r' on (?:unknown )?address| 0x|: ', m.group(2))[0][:60])
    m = re.search(r'runtime error: ([^\n]{0,80})', out)
    if m:
        return 'UBSan: ' + m.group(1)
    return 'a signal'


NATIVE_DRAWS = 1000000          # a run that draws more values ends (runtime/fuzz_driver.c's budget): not counted


def run_native(qp, n, objs, law, runs, timeout, wall):
    """The law's native runs (runtime/fuzz_driver.c, ASan/UBSan), in chunks of seeds until `runs` seeds or `wall`
    seconds: the failing runs (a signal other than the per-run timeout), the timeouts, the runs that reached the end
    of the law, and the kind of the first failure."""
    ho = n.harness_obj(law)
    exe = os.path.join(n.b, law)
    if not ho or not n.link(ho, objs, exe, law):
        r = qp.sh(['gcc', '-fsyntax-only', '-w', '-I' + qp.FW + '/include', '-Iharness', 'harness/%s.c' % law],
                  cwd=n.tree, check=False, capture=True)
        err = [l for l in (r.stdout or '').splitlines() if 'error' in l] or ['link failed']
        return dict(error='does not build: ' + err[0][:200])
    res = dict(done=0, failed=0, timeouts=0, completed=0, error='')
    fails = []
    t0, seed = datetime.datetime.now(), 1
    while res['done'] < runs and (datetime.datetime.now() - t0).total_seconds() < wall:
        k = min(50, runs - res['done'])
        r = qp.sh([exe, str(k), str(seed), str(NATIVE_DRAWS), str(timeout)], check=False, capture=True,
                  env=dict(qp.NATIVE_ENV, ASAN_OPTIONS=qp.NATIVE_ENV['ASAN_OPTIONS'] + ':symbolize=0'),
                  timeout=k * (timeout + 5) + 60)
        out = r.stdout or ''
        if not re.search(r'^runs \d+: ok', out, re.M):
            res['error'] = 'no summary (exit %d)' % r.returncode
            break
        sig = re.findall(r'^seed (\d+): signal (\d+)( \(timeout\))?$', out, re.M)
        fails += [int(s) for s, _, t in sig if not t]
        res['timeouts'] += sum(1 for _, _, t in sig if t)
        m = re.search(r'completed (\d+) \(passed all assumes\)', out)
        res['completed'] += int(m.group(1)) if m else 0
        res['done'] += k
        seed += k
        if fails:            # one counterexample is enough
            break
    res['failed'] = len(fails)
    if fails:
        one = qp.sh([exe, '1', str(fails[0]), str(NATIVE_DRAWS), str(timeout)], check=False, capture=True,
                    env=qp.NATIVE_ENV, timeout=timeout + 60)
        res['first'] = 'seed %d: %s' % (fails[0], native_failure(one.stdout or ''))
    return res


def run_interp(qp, tree, law, seeds, timeout):
    env = {'GP_INTERP_TIMEOUT': str(timeout)}
    e = qp.env_file(tree, law)
    if e:
        env['GP_ENV'] = os.path.join(tree, e)
    r = qp.sh([qp.FW + '/tools/interp.sh', qp.CONF, 'harness/%s.c' % law, '1', str(seeds)], cwd=tree, check=False,
              capture=True, env=env, coq=True, timeout=seeds * (timeout + 60) + 120)
    out = r.stdout or ''
    m = re.search(r'runs \d+: no stop \((\d+) skipped', out)
    if m:
        return dict(stop=False, skipped=int(m.group(1)))
    m = re.search(r'^seed (\d+): Stuck state', out, re.M)
    if m and not re.search(r'Stuck state:|Undefined behavior', out[m.end():]):
        lines = out[m.end():].splitlines()
        err = [l for l in lines if re.search(r':\d+:(\d+:)? .*error', l)] or \
            [l for l in lines if re.search(r'\berror\b', l) and 'warning' not in l and 'counterexample' not in l]
        return dict(stop=None, what='no verdict: the interpreter does not compile the law: %s'
                    % ' '.join((err or ['?'])[0].split())[-160:])
    if m:
        tail = out[m.end():]
        st = re.search(r'Stuck state: ([^\n]*)', tail)
        fn = re.search(r'in function (\w+)', tail)
        if (fn and fn.group(1) == 'gp_assert') or (st and 'gp_assert' in st.group(1)):
            what = 'a check failed (gp_assert)'
        elif st:
            what = 'undefined behaviour: %s%s' % (' '.join(st.group(1).split())[:120], ' in %s' % fn.group(1) if fn else '')
        else:
            err = [l for l in tail.splitlines() if 'error' in l.lower() and 'warning' not in l.lower()]
            what = 'stop: ' + ' '.join((err or tail.strip().splitlines()[-1:] or ['?'])[0].split())[:160]
        return dict(stop=True, seed=int(m.group(1)), what=what)
    return dict(stop=None, what='no verdict (exit %d): %s' % (r.returncode, ' '.join(out.strip().splitlines()[-2:])[:160]))


def agreement(expected, nat, itp):
    if nat.get('error'):
        return 'no verdict (the law does not build or run natively)'
    found = (nat.get('failed') or 0) > 0 or itp.get('stop') is True
    notes = []
    if not nat.get('completed'):
        notes.append('no native run reached the end')
    if itp.get('stop') is None:
        notes.append('no verdict from the interpreter')
    note = ' (%s)' % '; '.join(notes) if notes else ''
    if expected == 'false':
        return 'agrees: counterexample found' if found else 'not confirmed: no counterexample in these runs' + note
    if expected == 'true':
        return 'DISAGREES: counterexample to a task expected true' if found else 'agrees: no counterexample' + note
    return ('counterexample found' if found else 'no counterexample' + note)


def verdicts(qp, p, argv):
    a = argparse.ArgumentParser(prog='qp import-svcomp NAME --verdicts', add_help=False)
    a.add_argument('--verdicts', action='store_true')
    a.add_argument('laws', nargs='*')
    a.add_argument('-n', '--runs', type=int, default=1000)
    a.add_argument('--timeout', type=int, default=2, help='per native run (s)')
    a.add_argument('--budget', type=int, default=300, help='native wall time per law (s)')
    a.add_argument('--interp', type=int, default=3, metavar='N', help='seeds under the interpreter')
    a.add_argument('--interp-timeout', type=int, default=10, help='per interpreter seed (s)')
    a.add_argument('--out')
    o = a.parse_args(argv)
    known = imported_laws(p.dir)
    laws = o.laws or sorted(known)
    bad = [l for l in laws if l not in known]
    if bad:
        die('not laws of tools/qp import-svcomp in %s: %s' % (p.dir, ', '.join(bad)))
    if not laws:
        die('no imported law in %s' % p.dir)
    tree = law_tree(qp, p, laws)
    n = qp.Native(tree)
    objs, err = n.lib_objs()
    if objs is None:
        die('library build failed: ' + err[-1000:])
    rows, disagree = [], 0
    for law in laws:
        f = known[law]
        expected = (f.get('law', '').split() + ['unknown', 'unknown'])[1]
        prop = dict(kv.split('=', 1) for kv in f.get('options', '').split() if '=' in kv).get('property', '?')
        task_v = dict(re.findall(r'([\w-]+) (\w+)', f.get('verdicts', ''))).get(prop, 'none')
        nat = run_native(qp, n, objs, law, o.runs, o.timeout, o.budget)
        itp = run_interp(qp, tree, law, o.interp, o.interp_timeout) if o.interp and not nat.get('error') \
            else {'stop': False, 'skipped': 0}
        ag = agreement(expected, nat, itp)
        disagree += ag.startswith('DISAGREES')
        nat_s = nat['error'] if nat.get('error') else '%d of %d runs failed%s, %d timed out, %d reached the end' % (
            nat['failed'], nat['done'], ' (first: %s)' % nat['first'] if nat.get('first') else '', nat['timeouts'],
            nat['completed'])
        itp_s = '-' if not o.interp or nat.get('error') else (
            'no stop (%d of %d seeds timed out)' % (itp['skipped'], o.interp) if itp['stop'] is False else
            'stop at seed %d: %s' % (itp['seed'], itp['what']) if itp['stop'] else itp['what'])
        rows.append((law, prop, task_v, expected, nat_s, itp_s, ag))
        print('%s (%s, task %s, law expected %s)\n  native: %s\n  interpreter: %s\n  => %s'
              % (law, prop, task_v, expected, nat_s, itp_s, ag), flush=True)
    now = datetime.datetime.now().strftime('%Y-%m-%d %H:%M')
    L = ['# %s: the imported SV-COMP laws against their expected verdicts' % p.name, '',
         'By `tools/qp import-svcomp %s --verdicts` on %s: upstream %s, quickproof %s. Each law ran up to %d times '
         'natively (ASan/UBSan, %d s per run; exit and abort end a run without error) and on %d seeds under CompCert\'s '
         'interpreter (%d s per seed). A failing run or an interpreter stop is a counterexample to the law; a law '
         'expected false should show one, a law expected true should not. Random runs are not a proof either way: '
         'an expected-false law without a counterexample here may need a witness, and an expected-true law is only '
         'ready for a proof.' % (p.name, now, p.commit[:12], p.framework_label(), o.runs, o.timeout, o.interp,
                                 o.interp_timeout), '',
         '| law | property | task expected | law expected | native | interpreter | verdict |',
         '|---|---|---|---|---|---|---|']
    L += ['| `%s` | %s | %s | %s | %s | %s | %s |' % r for r in rows]
    L.append('')
    out = o.out or os.path.join(p.dir, 'SVCOMP.md')
    open(out, 'w').write('\n'.join(L))
    print('wrote %s' % out)
    return 1 if disagree else 0


def main(qp, p, argv):
    """Entry point of `tools/qp import-svcomp NAME ...` (argv: what follows NAME)."""
    if '--verdicts' in argv:
        raise SystemExit(verdicts(qp, p, argv))
    if not argv or argv[0].startswith('-'):
        die('usage: qp import-svcomp NAME TASK.yml [--property P] [--law L] [--malloc may-fail|never-fails] '
            '[--no-check] [--contract]\n       qp import-svcomp NAME --verdicts [LAW..] [-n RUNS] [--timeout S] '
            '[--interp N] [--interp-timeout S] [--out FILE]')
    import_task(qp, p, argv)
