CLANG_FLAGS = ['-std=gnu11', '-w', '-Wno-implicit-function-declaration', '-Wno-int-conversion',
               '-Wno-incompatible-function-pointer-types', '-Wno-incompatible-pointer-types',
               '-Wno-builtin-macro-redefined', '-Wno-error', '-ferror-limit=20']


def clang_flags(flags):
    """The importer's flags for clang: gcc's own include directory (qp new puts it in INC) is left out, clang
    has its own."""
    gcc_inc = run(['gcc', '-print-file-name=include']).stdout.strip()
    out, skip = [], False
    for i, f in enumerate(flags):
        if skip:
            skip = False
            continue
        if f == '-isystem' and i + 1 < len(flags) and os.path.realpath(flags[i + 1]) == os.path.realpath(gcc_inc):
            skip = True
            continue
        if f.startswith('-isystem') and os.path.realpath(f[8:]) == os.path.realpath(gcc_inc):
            continue
        out.append(f)
    return out


def clang_ast(src, flags, shim, cwd):
    r = run(['clang', '-Xclang', '-ast-dump=json', '-fsyntax-only'] + CLANG_FLAGS + ['-include', shim] +
            clang_flags(flags) + [src], cwd=cwd)
    if r.returncode:
        errs = [l for l in r.stderr.splitlines() if 'error:' in l][:5]
        raise Refused('the harness code is rejected by a C compiler (clang), although CBMC may accept it: %s'
                      % ' | '.join(e.replace(cwd + '/', '') for e in errs)[:600])
    return json.loads(r.stdout)


def clang_preprocess(src, flags, shim, cwd):
    r = run(['clang', '-E'] + CLANG_FLAGS + ['-include', shim] + clang_flags(flags) + [src], cwd=cwd)
    return r.stdout if r.returncode == 0 else ''


def callee_name(n):
    inner = n.get('inner') or []
    c = inner[0] if inner else {}
    while c.get('kind') in ('ImplicitCastExpr', 'ParenExpr', 'CStyleCastExpr') and c.get('inner'):
        c = c['inner'][0]
    return (c.get('referencedDecl') or {}).get('name')


def calls_in(n, name):
    if n.get('kind') == 'CallExpr' and callee_name(n) == name:
        return True
    return any(calls_in(c, name) for c in n.get('inner', []) or [])


class Analysis:
    """One harness source through clang's JSON AST: the insertions after uninitialised locals, the typed
    allocations, the nondet functions, the entry function, and the contexts of pointer-validity predicates."""

    def __init__(self, src, rel, types, cbmc_root):
        self.src, self.rel, self.types = os.path.realpath(src), rel, types
        self.text = open(src, 'rb').read()
        self.cbmc_root = cbmc_root
        self.inserts, self.replaces, self.edits = [], [], []
        self.nondet = {}          # name -> (qualType, implicit)
        self.used = set()
        self.defined = {}         # function name -> file of its body
        self.entry_params = {}    # function name -> [(name, qualType)]
        self.mem_contexts = []    # (predicate, context)
        self.uninterp = {}        # qp_cbmc_uninterpreted_NAME -> qualType
        self.uninterp_implicit = {}
        self.bodies = set()       # ids of function definitions
        self.unproto_calls = set()
        self.refusals, self.warnings = [], []
        self.locals = []          # (function, variable, type, macro)

    def run(self, ast):
        state = {'file': None}
        self.walk(ast, state, [], [])

    def loc(self, l, state):
        if not isinstance(l, dict):
            return
        for k in ('spellingLoc', 'expansionLoc'):
            if k in l:
                self.loc(l[k], state)
        if 'file' in l:
            state['file'] = l['file']

    def main_file(self, f):
        return f is not None and os.path.realpath(f) == self.src

    def harness_file(self, f):
        return f is not None and os.path.realpath(f).startswith(self.cbmc_root + os.sep)

    def walk(self, n, state, parents, funcs):
        self.loc(n.get('loc'), state)
        rng = n.get('range') or {}
        self.loc(rng.get('begin'), state)
        f = state['file']
        self.loc(rng.get('end'), state)
        k = n.get('kind')
        if k == 'RecordDecl':
            self.types.record_decl(n, f, bool(funcs))
        elif k == 'TypedefDecl':
            if not funcs:
                self.types.typedef_decl(n)
        elif k == 'FunctionDecl':
            name = n.get('name', '')
            body = any(c.get('kind') == 'CompoundStmt' for c in n.get('inner', []) or [])
            if body:
                self.bodies.add(n.get('id'))
                self.defined.setdefault(name, f)
                self.entry_params[name] = [(c.get('name'), c.get('type', {}).get('qualType', ''))
                                           for c in n.get('inner', []) or [] if c.get('kind') == 'ParmVarDecl']
            elif name.startswith(('nondet_', '__VERIFIER_nondet_')):
                self.nondet[name] = (n.get('type', {}).get('qualType', ''), False)
            if name.startswith('qp_cbmc_uninterpreted_'):
                self.uninterp.setdefault(name, n.get('type', {}).get('qualType', ''))
            funcs = funcs + [(name, f)] if body else funcs
        elif k == 'DeclRefExpr':
            ref = n.get('referencedDecl') or {}
            if ref.get('kind') == 'FunctionDecl':
                nm = ref.get('name', '')
                self.used.add(nm)
                if nm.startswith(('nondet_', '__VERIFIER_nondet_')) and nm not in self.nondet:
                    self.nondet[nm] = ((ref.get('type') or {}).get('qualType', 'int ()'), True)
                if nm.startswith('qp_cbmc_uninterpreted_') and nm not in self.uninterp:
                    self.uninterp[nm] = (ref.get('type') or {}).get('qualType', 'int ()')
                    self.uninterp_implicit[nm] = True
        elif k == 'CallExpr' and funcs:
            name = callee_name(n)
            ref = self.callee_ref(n)
            if ref and re.search(r'\(\)$', (ref.get('type') or {}).get('qualType', '')) and \
                    ref.get('id') not in self.bodies and self.harness_file(f):
                self.unproto_calls.add(name)
            if name in MEM_PREDICATES:
                self.mem_contexts.append((name, self.mem_context(n, parents)))
            if name == 'qp_cbmc_malloc' and len(n.get('inner') or []) == 2 and self.main_file(f):
                self.typed_malloc(n)
        elif k == 'DeclStmt' and funcs:
            self.decl_stmt(n, f, parents, funcs)
        for c in n.get('inner', []) or []:
            self.walk(c, state, parents + [n], funcs)

    @staticmethod
    def callee_ref(n):
        inner = n.get('inner') or []
        c = inner[0] if inner else {}
        while c.get('kind') in ('ImplicitCastExpr', 'ParenExpr') and c.get('inner'):
            c = c['inner'][0]
        return c.get('referencedDecl') if c.get('kind') == 'DeclRefExpr' else None

    def mem_context(self, call, parents):
        """'assertion', 'assumption', 'unevaluated' or 'other': where a pointer-validity predicate sits, through
        parentheses, casts, && and || and the shim's `!= 0` only (a positive position)."""
        child = call
        for p in reversed(parents):
            k = p.get('kind')
            if k == 'CallExpr':
                name = callee_name(p)
                if name in ('gp_assert', 'qp_assert'):
                    return 'assertion'
                if name in ('gp_assume', 'qp_assume'):
                    return 'assumption'
                return 'other'
            if k == 'UnaryExprOrTypeTraitExpr':
                return 'unevaluated'
            if k == 'IfStmt':
                inner = p.get('inner') or []
                if inner and inner[0] is child and any(calls_in(c, '__assert_fail') for c in inner[1:]):
                    return 'assertion'
                return 'other'
            if k in ('ParenExpr', 'ImplicitCastExpr', 'CStyleCastExpr'):
                child = p
                continue
            if k == 'BinaryOperator' and p.get('opcode') in ('&&', '||'):
                child = p
                continue
            if k == 'BinaryOperator' and p.get('opcode') == '!=':
                other = [c for c in p.get('inner') or [] if c is not child]
                if other and other[0].get('kind') == 'IntegerLiteral' and other[0].get('value') == '0':
                    child = p
                    continue
            return 'other'
        return 'other'

    @staticmethod
    def offset(l):
        if 'expansionLoc' in l:
            return l['expansionLoc'].get('offset'), l['expansionLoc'].get('tokLen', 0), True
        return l.get('offset'), l.get('tokLen', 0), False

    def typed_malloc(self, n):
        e = n['inner'][1]
        while e.get('kind') in ('ImplicitCastExpr', 'ParenExpr', 'CStyleCastExpr') and e.get('inner'):
            e = e['inner'][0]
        if not (e.get('kind') == 'UnaryExprOrTypeTraitExpr' and e.get('name') == 'sizeof'):
            return
        if 'argType' in e:
            qt = e['argType'].get('qualType', '')
        elif e.get('inner'):
            qt = e['inner'][0].get('type', {}).get('qualType', '')
        else:
            return
        d = self.types.resolve(qt)
        if d['k'] == 'bool':
            fn = 'qp_cbmc_malloc_scalar_bool()'
        elif d['k'] in ('ptr', 'fptr'):
            fn = 'qp_cbmc_malloc_scalar_pointer()'
        elif d['k'] == 'struct' and self.types.key(d['rid']):
            if d['rid'] not in self.types.wanted:
                self.types.wanted.append(d['rid'])
            fn = 'qp_cbmc_malloc_%s()' % self.types.key(d['rid'])
        else:
            return
        b = n['range']['begin']
        en = n['range']['end']
        bo, bl, _ = self.offset(b)
        eo, el, _ = self.offset(en)
        # the call's own text in the file: `malloc` (the shim's macro, or written out) ... `)`; a call that a
        # macro of the harness writes stays as it is
        if bo is None or eo is None or (('spellingLoc' in en or 'expansionLoc' in en) and
                                        not en.get('expansionLoc', {}).get('isMacroArgExpansion')) or \
                self.text[bo:bo + bl] != b'malloc' or self.text[eo:eo + el] != b')':
            self.warnings.append('%s: malloc(sizeof(%s)) written by a macro: arbitrary bytes, not typed' % (self.rel, qt))
            return
        self.replaces.append((bo, eo + el, fn))
        self.edits.append('malloc(sizeof(%s)) -> %s' % (qt, fn))

    def decl_stmt(self, n, f, parents, funcs):
        vars_ = [c for c in n.get('inner', []) or [] if c.get('kind') == 'VarDecl' and 'init' not in c
                 and c.get('storageClass') not in ('static', 'extern')]
        if not vars_:
            return
        fn = funcs[-1][0]
        if not self.main_file(f):
            if self.harness_file(f):
                self.refusals.append('uninitialised local %s in %s, a function of a harness header (%s): '
                                     'not rewritten' % (vars_[0].get('name'), fn, os.path.basename(f)))
            return
        end = (n.get('range') or {}).get('end') or {}
        if 'spellingLoc' in end or 'expansionLoc' in end:
            for c in vars_:
                self.refusals.append('uninitialised local %s of %s is declared by a macro' % (c.get('name'), fn))
            return
        parent = parents[-1].get('kind') if parents else None
        if parent != 'CompoundStmt':
            for c in vars_:
                self.refusals.append('uninitialised local %s of %s is declared outside a block (%s)'
                                     % (c.get('name'), fn, parent))
            return
        lines = []
        for c in vars_:
            name, qt = c.get('name'), c.get('type', {}).get('qualType', '')
            code = self.types.havoc(name, qt, '%s:%s:%s' % (self.rel, fn, name))
            lines += code
            text = ' '.join(l.strip() for l in code)
            m = re.search(r'\b(QP_CBMC_\w+|qp_cbmc_\w+)', text)
            label = (m.group(1) if m else 'NULL') + ('[]' if text.startswith('{') and 'for (' in text else '')
            self.locals.append((fn, name, qt, label if code else '-'))
        if lines:
            self.inserts.append((end['offset'] + end.get('tokLen', 1), ' ' + ' '.join(l.strip() for l in lines)))


def rewrite(text, inserts, replaces):
    edits = [(o, o, s) for o, s in inserts] + replaces
    out = text
    for b, e, s in sorted(edits, key=lambda x: (x[0], x[1]), reverse=True):
        out = out[:b] + s.encode() + out[e:]
    return out


def split_params(p):
    out, depth, cur = [], 0, ''
    for ch in p:
        if ch == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
            continue
        depth += ch in '(['
        depth -= ch in ')]'
        cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


EARLY_TYPES = {'void', 'char', 'short', 'int', 'long', 'signed', 'unsigned', '_Bool', 'bool', 'const', 'volatile',
               'restrict', 'size_t', 'ssize_t', 'ptrdiff_t', 'intptr_t', 'uintptr_t', 'int8_t', 'int16_t', 'int32_t',
               'int64_t', 'uint8_t', 'uint16_t', 'uint32_t', 'uint64_t', '__CPROVER_size_t', '__CPROVER_bool'}


def early(sig, name):
    """The declaration of a generated function can precede the harness code: its types are the C library's
    (or struct and union tags, which a declaration may leave incomplete)."""
    t = re.sub(r'\b(struct|union)\s+\w+', ' ', sig.replace(name, ' ', 1))
    t = re.sub(r'\bqp_a\d+\b', ' ', t)
    return all(w in EARLY_TYPES for w in re.findall(r'[A-Za-z_]\w*', t))


def value_function(name, qtype, types, what):
    """A definition of a body-less function that returns any value of its type (a nondet_* of the harness, or
    an uninterpreted function): the arguments ignored, no side effect."""
    m = re.match(r'^(.*?)\s*\((.*)\)(\s*__attribute__.*)?$', qtype.strip())
    if not m or '(' in m.group(1):
        raise Refused('%s %s: cannot read its type (%s)' % (what, name, qtype))
    ret = m.group(1).strip()
    params = [x for x in split_params(m.group(2)) if x not in ('', 'void')]
    plist, uses = [], []
    for i, t in enumerate(params):
        if '(' in t or '...' in t:
            raise Refused('%s %s has a parameter of type %s' % (what, name, t))
        plist.append('%s qp_a%d' % (t, i))
        uses.append('\t(void) qp_a%d;' % i)
    sig = '%s%s%s(%s)' % (ret, '' if ret.endswith('*') else ' ', name, ', '.join(plist) or 'void')
    if ret == 'void':
        body = []
    else:
        n0 = len(types.refusals)
        body = ['\t%s%sqp_v;' % (ret, '' if ret.endswith('*') else ' ')] + \
            ['\t' + l for l in types.havoc('qp_v', ret, name)] + ['\treturn qp_v;']
        if len(types.refusals) > n0:
            raise Refused(types.refusals.pop())
    return sig, '%s\n{\n%s\n}' % (sig, '\n'.join(uses + body))


