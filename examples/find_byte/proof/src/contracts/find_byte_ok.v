Lemma malloc_test_null (t: type) (q: val) (P: mpred):
  0 <= sizeof t ->
  (if eq_dec q nullval then emp else malloc_token Ews t q * data_at_ Ews t q) * P
  |-- denote_tc_test_eq q (Vlong (Int64.repr 0)).
Proof.
  intros Ht. destruct (eq_dec q nullval).
  - subst. simpl. entailer!.
  - destruct (zlt 0 (sizeof t)).
    + sep_apply (data_at__valid_ptr Ews t q); [ auto | lia | ]. entailer!.
    + sep_apply (malloc_token_valid_pointer Ews t q); [ lia | ]. entailer!.
Qed.

Lemma body_main: semax_body (QPvarspecs p) Gmain f_main (_main, main_spec_std p).
Proof.
  start_function.
  sep_apply (create_mem_mgr gv).
  forward_call. Intros n.
  forward_call.
  assert (Hn: n <= 1024).
  { revert H0. change (Int.signed (Int.repr 1024)) with 1024. unfold Int64.ltu.
    rewrite !Int64.unsigned_repr by rep_lia.
    if_tac; simpl; [ intros X; exfalso; apply X; reflexivity | lia ]. }
  forward_call (tarray tuchar n, gv).
  { simpl; rep_lia. }
  Intros q.
  forward_if (PROP (q <> nullval)
              LOCAL (temp _n (Vlong (Int64.repr n)); temp _buf q; gvars gv)
              SEP (mem_mgr gv; malloc_token Ews (tarray tuchar n) q; data_at_ Ews (tarray tuchar n) q; has_ext tt)).
  { apply derives_trans with ((if eq_dec q nullval then emp else
      malloc_token Ews (tarray tuchar n) q * data_at_ Ews (tarray tuchar n) q) * TT)%logic;
      [ cancel | apply malloc_test_null; simpl; rep_lia ]. }
  { forward. Exists (Int.repr 0). entailer!. }
  { forward. rewrite if_false by auto. entailer!. }
  Intros.
  forward_call (q, n, Ews).
  { rewrite if_false by auto. cancel. }
  Intros bs. rewrite if_false by auto. subst n.
  change (map (fun b => Vint (Int.repr b)) bs) with (F.bytes bs).
  forward_call. Intros c.
  forward_call (q, Ews, bs, c).
  Intros r.
  forward_call.
  { match goal with E: Int.repr (Z.b2z _) = Int.zero |- _ => revert E end.
    unfold Int64.ltu. rewrite !Int64.unsigned_repr by rep_lia.
    if_tac; [ lia | simpl; intro X; discriminate X ]. }
  forward_if (PROP ()
              LOCAL (temp _n (Vlong (Int64.repr (Zlength bs))); temp _buf q; gvars gv)
              SEP (data_at Ews (tarray tuchar (Zlength bs)) (F.bytes bs) q;
                   mem_mgr gv; malloc_token Ews (tarray tuchar (Zlength bs)) q; has_ext tt)).
  - assert (Hx: 0 <= Znth r bs <= Byte.max_unsigned) by (apply (proj1 (Forall_Znth _ _) H3); lia).
    forward.
    { entailer!. rewrite F.Znth_bytes by lia. simpl. rewrite Int.unsigned_repr by rep_lia. rep_lia. }
    rewrite F.Znth_bytes by lia.
    forward_call.
    { match goal with E: Int.repr (Z.b2z _) = Int.zero |- _ => revert E end.
      match goal with Hf: _ < _ -> Znth r bs = c |- _ => rewrite Hf by lia end.
      rewrite Int.eq_true. simpl. intro X; discriminate X. }
    entailer!.
  - forward. entailer!.
  - sep_apply (data_at_data_at_ Ews (tarray tuchar (Zlength bs)) (F.bytes bs) q).
    forward_call (tarray tuchar (Zlength bs), q, gv).
    { rewrite if_false by auto. cancel. }
    forward.
    Exists (Int.repr 0). entailer!.
Qed.

