#!/usr/bin/env python3
"""tests/qp/test_helpers.py: a test of two helpers of tools/qp.

  - statement_code, the textual statement check of `qp rebuild`: a contract whose law is proved in the contract
    file itself, with Require and Import lines added before the theorem, keeps the generated statement; a changed
    program or theorem does not;
  - njobs, the parallel jobs of Coq builds and native runs: QP_JOBS when it is set, half and a quarter of the CPUs
    otherwise, and a value that is not a positive integer is refused;
  - prebuild, the build of run/prebuild in qp verify: a build product of a main source that was there before
    (a resumed run keeps what it built) is not counted, one that the prebuild builds is refused.
Exit 0 = pass."""
import importlib.machinery
import importlib.util
import os
import sys

sys.dont_write_bytecode = True
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.realpath(__file__))))
loader = importlib.machinery.SourceFileLoader('qp', os.path.join(ROOT, 'tools', 'qp'))
spec = importlib.util.spec_from_loader('qp', loader)
qp = importlib.util.module_from_spec(spec)
loader.exec_module(qp)

GENERATED = """(* Generated by tools/new_contract.py from /some/path/harness/law.c. *)
Require Import VST.floyd.proofauto.
Require Import QuickProof.Contract.
Require Demo.harness.law.code.

Module Harness.
  #[local] Instance CS : compspecs. make_compspecs Demo.harness.law.code.prog. Defined.
  Definition qp := ltac:(QPprog Demo.harness.law.code.prog).
End Harness.

Definition whole_prog := ltac:(QPlink_progs Harness.qp Libc.qp).

Theorem law : harness_safe whole_prog.
Admitted.
"""

fails = 0


def check(cond, what):
    global fails
    print('%s %s' % ('ok  ' if cond else 'FAIL', what))
    fails += not cond


want = qp.statement_code(GENERATED)
proved = GENERATED.replace('Require Demo.harness.law.code.\n',
                           'Require Demo.harness.law.code.\nRequire Import Demo.proof.Specs.\n'
                           'From Coq Require Import Lists.List.\nImport ListNotations.\n')
proved = proved.replace('Theorem law : harness_safe whole_prog.\nAdmitted.\n',
                        'Theorem law : harness_safe whole_prog.\nProof. exact Demo.proof.Main.law_proof. Qed.\n')
check(want is not None and qp.statement_code(proved) == want,
      'statement_code: Require, From ... Require and Import lines added before the theorem keep the statement')
check(qp.statement_code(GENERATED.replace('/some/path', '/other/path')) == want,
      'statement_code: a comment (the generated header) does not count')
check(qp.statement_code(proved.replace('Libc.qp).', 'Libc.qp Extra.qp).')) != want,
      'statement_code: a changed whole_prog differs')
check(qp.statement_code(proved.replace('Theorem law : harness_safe whole_prog.',
                                       'Definition harness_safe (p : unit) := True.\n'
                                       'Theorem law : harness_safe whole_prog.')) != want,
      'statement_code: a definition added before the theorem differs')
check(qp.statement_code('Lemma x : True. Proof. auto. Qed.\n') is None, 'statement_code: no law theorem: None')

cpus = os.cpu_count() or 4
qp.SITE['QP_JOBS'] = ''
check(qp.njobs(build=True) == max(2, cpus // 2) and qp.njobs() == max(1, cpus // 4),
      'njobs: without QP_JOBS, half the CPUs for a build and a quarter for runs')
qp.SITE['QP_JOBS'] = '3'
check(qp.njobs(build=True) == 3 and qp.njobs() == 3, 'njobs: QP_JOBS=3 for builds and runs')
for bad in ('0', 'x', '-2'):
    qp.SITE['QP_JOBS'] = bad
    try:
        qp.njobs()
        refused = False
    except SystemExit:
        refused = True
    check(refused, 'njobs: QP_JOBS=%s is refused' % bad)

import shutil
import tempfile
d = tempfile.mkdtemp()
for sub in ('src', 'vend', 'run'):
    os.makedirs(os.path.join(d, sub))
open(os.path.join(d, '_CoqProject'), 'w').write('-R src T\nsrc/a.v\n')
open(os.path.join(d, 'src', 'a.v'), 'w').write('Definition a := 0.\n')
open(os.path.join(d, 'src', 'a.vo'), 'w').write('left by an interrupted run\n')
open(os.path.join(d, 'run', 'prebuild'), 'w').write('vend\n')
open(os.path.join(d, 'vend', '_CoqProject'), 'w').write('-R . V\nb.v\n')
open(os.path.join(d, 'vend', 'b.v'), 'w').write('Definition b := 1.\n')
qp.SITE['QP_JOBS'] = '2'
ok, line = qp.prebuild(d, git=False)
check(ok, 'prebuild: a build product that was there before it ran is not counted (%s)' % line)
os.remove(os.path.join(d, 'src', 'a.vo'))
open(os.path.join(d, 'vend', '_CoqProject'), 'w').write('-R . V\n-R ../src T\nb.v\n../src/a.v\n')
ok, line = qp.prebuild(d, git=False)
check(not ok and 'src/a.vo' in (line or ''), 'prebuild: building a source of the main build is refused (%s)' % line)
shutil.rmtree(d)
sys.exit(1 if fails else 0)
