#!/usr/bin/env python3
"""quickproof tools/new_contract.py CONFIG LOGICAL: write the Coq contracts of a project, one theorem per harness.

CONFIG is the project's quickproof.conf (tools/clight.sh), LOGICAL the Coq logical root of `src` in the
project's _CoqProject (`-R src LOGICAL`).  Units whose output directory is under src/harness/ are
harnesses; the others are the code under test (library units, the framework's libc and malloc unit).

Writes
  src/units.v                    one module per library unit: its compspecs and its QP.program;
  src/contracts/<harness>.v      the library units linked with that harness into whole_prog, and
                                 Theorem <harness> : harness_safe whole_prog  (Admitted);
  src/contracts/suite.v          with two or more harnesses: Theorem suite, the conjunction of all laws,
                                 so that one proof covers them all on one shared layer.
Existing files are not overwritten unless --force is given (the statement is frozen once proved).
Run tools/clight.sh first: the generated code.v files must exist.

Linking (quickproof.conf `LINK=`): by default (`all`) every library unit is linked into every law's program.
With `LINK=per-law` each law's program links only the units it needs, the closure of its harness under
references computed by tools/link_units.py (`UNITS_<law>=(...)` fixes a law's units, checked); the contract
records the units, and Lemma whole_prog_undefined checks by computation which globals the program declares
without defining (QuickProof.Link).  docs/LINKING.md: the design and why it is sound.
"""
import argparse
import os
import re
import subprocess
import sys

sys.dont_write_bytecode = True   # no __pycache__ in the framework's checkout (a submodule of proving repositories)
sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
import link_units  # noqa: E402


def units_of(config):
    link_units.check_conf(config)
    gp = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
    out = subprocess.run(['bash', '-c', 'cd "$(dirname "$1")"; GP="$2"; INC=(); DEFS=(); UNITS=(); '
                          'source "$1"; printf "%s\\n" "${UNITS[@]}"', '_', os.path.realpath(config), gp],
                         check=True, capture_output=True, text=True).stdout
    return [line.split('=', 1) for line in out.splitlines() if line]


def module_name(outdir):
    parts = re.split(r'[^A-Za-z0-9]+', os.path.basename(outdir.rstrip('/')))
    return ''.join(p[:1].upper() + p[1:] for p in parts if p) or 'Unit'


def coq_path(logical, outdir):
    rel = os.path.relpath(outdir, 'src')
    return '.'.join([logical] + rel.split(os.sep) + ['code'])


def wrap_words(words, indent, width=100):
    lines, line = [], indent
    for w in words:
        if len(line) + len(w) + 1 > width and line.strip():
            lines.append(line.rstrip()); line = indent
        line += w + ' '
    lines.append(line.rstrip())
    return '\n'.join(lines)


def per_law_contract(logical, src, out, name, hp, mods, libs, law):
    """The contract of a law under LINK=per-law: its own units only, recorded, and the undefined-globals check."""
    units, how, dropped, undefined = law
    mod = {o: m for (m, _, _), (_, o) in zip(mods, libs)}
    srcs = {o: os.path.relpath(s) for s, o in libs}
    link, prev = [], ('%s.qp' % mod[units[0]]) if units else None
    for u in units[1:]:
        link.append('Definition link_%s := ltac:(QPlink_progs %s.qp %s).' % (mod[u], mod[u], prev))
        prev = 'link_%s' % mod[u]
    names = ['"%s"' % g for g in undefined]
    return """(* ======================================================================
   CONTRACT: %(src)s, generated by quickproof/tools/new_contract.py.

   The theorem is QuickProof.Contract.harness_safe of the whole program: the
   harness %(src)s linked with the units it needs (per-law linking,
   LINK=per-law in quickproof.conf; docs/LINKING.md of the framework):
%(units)s.
   By VST's adequacy theorem, in the honest external world QuickProof.Env: for
   every value the nondet_* functions may return, no execution has undefined
   behaviour; the harness executes undefined behaviour exactly when one of
   its checks fails, so the theorem says its checks hold in every execution.
   What the checks are is written in the harness file.
   ====================================================================== *)

(* THE UNITS (%(how)s, quickproof/tools/link_units.py): the closure of the
   harness under references.  A unit is linked when it defines a global (a
   function with a body, a variable with an initialiser) that a linked unit
   references without defining it, and then with all its definitions.  So
   every global this program references is resolved as in the program of all
   units; the units left out are referenced by no linked unit:
%(dropped)s. *)

Require Import VST.floyd.proofauto.
Require Import VST.floyd.VSU.
Require Import QuickProof.Contract.
Require QuickProof.Link.
%(requires)s
Require %(hp)s.

Module Harness.
  #[local] Instance CS : compspecs. make_compspecs %(hp)s.prog. Defined.
  Definition qp := ltac:(QPprog %(hp)s.prog).
End Harness.

(* The link must succeed (`Errors.OK`); the order is irrelevant. *)
%(link)s
%(whole)s

(* The globals whole_prog declares without defining, besides the functions of
   the environment with their signatures (QuickProof.Link.undefined_globals):
   exactly those that no unit of the project defines, as in the program of all
   units.  By QuickProof.Link.honest_rejects_foreign the environment gives such an
   external function no behaviour: a proved program never calls one. *)
Local Open Scope string_scope.
Lemma whole_prog_undefined : QuickProof.Link.undefined_globals_are whole_prog
%(names)s
  ]%%list = true.
Proof. vm_compute. reflexivity. Qed.

(* ---------------------------------------------------------------------- *)
(* THE THEOREM.                                                            *)
(* ---------------------------------------------------------------------- *)
Theorem %(name)s : harness_safe whole_prog.
Proof.
Admitted.
""" % dict(src=src, name=name, hp=hp, link='\n'.join(link),
           requires='\n'.join('Require %s.units.%s.' % (logical, mod[u]) for u in units),
           whole=('Definition whole_prog := ltac:(QPlink_progs Harness.qp %s).' % prev) if prev else
                 'Definition whole_prog := Harness.qp.',
           units=wrap_words([srcs[u] + ',' for u in units[:-1]] + [srcs[units[-1]]], '     ') if units else '     (none)',
           how='computed' if how == 'computed' else 'fixed by %s in quickproof.conf, checked closed' % how,
           dropped=wrap_words([srcs[d] + ',' for d in dropped[:-1]] + [srcs[d] for d in dropped[-1:]], '     ')
           if dropped else '     none',
           names=wrap_words(['['] + [n + ';' for n in names[:-1]] + names[-1:], '  ') if names else '  [')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('config')
    ap.add_argument('logical')
    ap.add_argument('--force', action='store_true')
    ap.add_argument('--suite-exclude', default='', help='comma-separated laws left out of suite (e.g. known false)')
    a = ap.parse_args()
    os.chdir(os.path.dirname(os.path.realpath(a.config)))
    units = units_of(a.config)
    libs = [(src, out) for src, out in units if not out.startswith('src/harness/')]
    harnesses = [(src, out) for src, out in units if out.startswith('src/harness/')]
    if not harnesses:
        sys.exit('no harness unit (output directory under src/harness/) in %s' % a.config)
    for _, out in units:
        if not os.path.exists(os.path.join(out, 'code.v')):
            sys.exit('%s/code.v missing: run tools/clight.sh first' % out)
    per_law = {}      # LINK=per-law: harness output dir -> (library units, how, units not linked, undefined globals)
    per_law_mode = (link_units.conf_values(a.config, ['LINK'])['LINK'] or ['all']) != ['all']
    if per_law_mode:
        try:
            proj = link_units.Project(a.config)
            per_law = {out: proj.law(out) for _, out in harnesses}
        except ValueError as e:
            sys.exit('new_contract: %s (no contract written)' % e)

    def write(path, text):
        if os.path.exists(path) and not a.force:
            print('kept %s (exists; --force to overwrite)' % path)
            return
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, 'w').write(text)
        print('wrote %s' % path)

    mods = [(module_name(out), coq_path(a.logical, out), src) for src, out in libs]
    units_v = ["(* CONTRACT: the units of the code under test, generated by quickproof/tools/new_contract.py.",
               "   Each unit's `prog` is the clightgen output (quickproof/tools/clight.sh), never edited by hand,",
               "   lifted to a QP.program; the lift needs the unit's own compspecs, hence one module per unit. *)",
               "Require Import VST.floyd.proofauto.", "Require Import VST.floyd.VSU."]
    units_v += ['Require %s.' % p for _, p, _ in mods]
    for m, p, src in mods:
        units_v += ['', '(* %s *)' % os.path.relpath(src), 'Module %s.' % m,
                    '  #[local] Instance CS : compspecs. make_compspecs %s.prog. Defined.' % p,
                    '  Definition qp := ltac:(QPprog %s.prog).' % p, 'End %s.' % m]
    if not per_law_mode:
        write('src/units.v', '\n'.join(units_v) + '\n')
    else:
        # one file per unit, so that a law's contract builds only the units it links
        if len(set(m for m, _, _ in mods)) != len(mods):
            sys.exit('new_contract: two units with one module name: %s' % ', '.join(m for m, _, _ in mods))
        for m, p, src in mods:
            write('src/units/%s.v' % m, '\n'.join([
                "(* CONTRACT: the unit %s of the code under test, generated by quickproof/tools/new_contract.py" % os.path.relpath(src),
                "   (per-law linking: one file per unit).  Its `prog` is the clightgen output (quickproof/tools/clight.sh),",
                "   never edited by hand, lifted to a QP.program; the lift needs the unit's own compspecs, CS. *)",
                "Require Import VST.floyd.proofauto.", "Require Import VST.floyd.VSU.", "Require %s." % p, "",
                "#[local] Instance CS : compspecs. make_compspecs %s.prog. Defined." % p,
                "Definition qp := ltac:(QPprog %s.prog)." % p]) + '\n')

    for src, out in harnesses:
        src = os.path.relpath(src)
        name = os.path.basename(out.rstrip('/'))
        hp = coq_path(a.logical, out)
        link = []
        prev = '%s.qp' % mods[0][0]
        for m, _, _ in mods[1:]:
            link.append('Definition link_%s := ltac:(QPlink_progs %s.qp %s).' % (m, m, prev))
            prev = 'link_%s' % m
        text = """(* ======================================================================
   CONTRACT: %(src)s, generated by quickproof/tools/new_contract.py.

   The theorem is QuickProof.Contract.harness_safe of the whole program: the
   harness %(src)s linked with the units of %(units)s.
   By VST's adequacy theorem, in the honest external world QuickProof.Env: for
   every value the nondet_* functions may return, no execution has undefined
   behaviour; the harness executes undefined behaviour exactly when one of
   its checks fails, so the theorem says its checks hold in every execution.
   What the checks are is written in the harness file.
   ====================================================================== *)

Require Import VST.floyd.proofauto.
Require Import VST.floyd.VSU.
Require Import QuickProof.Contract.
Require Import %(logical)s.units.
Require %(hp)s.

Module Harness.
  #[local] Instance CS : compspecs. make_compspecs %(hp)s.prog. Defined.
  Definition qp := ltac:(QPprog %(hp)s.prog).
End Harness.

(* The link must succeed (`Errors.OK`); the order is irrelevant. *)
%(link)s
Definition whole_prog := ltac:(QPlink_progs Harness.qp %(prev)s).

(* ---------------------------------------------------------------------- *)
(* THE THEOREM.                                                            *)
(* ---------------------------------------------------------------------- *)
Theorem %(name)s : harness_safe whole_prog.
Proof.
Admitted.
""" % dict(src=src, units=', '.join(os.path.relpath(s) for _, _, s in mods), logical=a.logical, hp=hp,
           link='\n'.join(link), prev=prev, name=name)
        if out in per_law:
            text = per_law_contract(a.logical, src, out, name, hp, mods, libs, per_law[out])
        write('src/contracts/%s.v' % name, text)

    excl = set(x for x in a.suite_exclude.split(',') if x)
    names = [os.path.basename(out.rstrip('/')) for _, out in harnesses if os.path.basename(out.rstrip('/')) not in excl]
    if len(names) >= 2:
        mods = ['%s.contracts.%s' % (a.logical, n) for n in names]
        text = """(* ======================================================================
   CONTRACT: every law of the project in one theorem, generated by
   quickproof/tools/new_contract.py.

   Proving `suite` in one worktree makes all laws share one model and one
   specification per function of the code under test.  It needs the proof of
   every theorem in src/contracts/*.v: an Admitted law shows up in
   Print Assumptions of `suite`.
   ====================================================================== *)

Require Import QuickProof.Contract.
%(requires)s

Theorem suite :
  %(conj)s.
Proof.
Admitted.
""" % dict(requires='\n'.join('Require %s.' % m for m in mods),
             conj=' /\\\n  '.join('harness_safe %s.whole_prog' % m for m in mods))
        write('src/contracts/suite.v', text)


if __name__ == '__main__':
    main()
