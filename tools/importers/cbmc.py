ASSIGN = re.compile(r'^(?:override\s+|export\s+)?([A-Za-z_][A-Za-z0-9_.-]*)\s*(\+=|\?=|::=|:=|!=|=)\s*(.*?)\s*$')
COND = re.compile(r'^(ifeq|ifneq|ifdef|ifndef)\b')


class Make:
    """The variables of a Makefile and the files it includes, evaluated in order as make reads them: `=` and
    `?=` are recursive (expanded when used), `:=` is expanded at once, `+=` appends.  The predefined variables
    and --set are fixed (as on make's command line).  Conditional blocks (ifeq ... endif) and define blocks
    are skipped, `$(shell ...)` and `!=` are never run (their value is empty), and both are reported when they
    concern a variable the importer uses.  Relative include paths are relative to the proof directory, where
    the starter kit runs make."""

    def __init__(self, cwd, fixed, follow=True):
        self.cwd, self.follow = cwd, follow
        self.vars = {k: ('simple', v) for k, v in fixed.items()}
        self.fixed = set(fixed)
        self.assigned = {}           # name -> first value assigned in the Makefiles (raw text)
        self.files = []              # the Makefiles read, in order
        self.notes = []

    def read(self, path):
        path = os.path.realpath(path)
        if path in self.files or not os.path.isfile(path):
            return
        self.files.append(path)
        depth, cont, in_define, lineno = 0, '', False, 0
        for raw in open(path, errors='replace').read().split('\n'):
            lineno += 1
            line = cont + raw
            if line.endswith('\\'):
                cont = line[:-1] + ' '
                continue
            cont = ''
            if line.startswith('\t'):
                continue                                  # a recipe line
            line = re.sub(r'(?<!\\)#.*$', '', line)
            s = line.strip()
            if in_define:
                in_define = not re.match(r'^endef\b', s)
                continue
            if re.match(r'^define\b', s):
                in_define = True
                continue
            if COND.match(s):
                depth += 1
                continue
            if s == 'endif' or s.startswith('endif '):
                depth = max(0, depth - 1)
                continue
            if not s or s == 'else' or s.startswith('else '):
                continue
            m = ASSIGN.match(s)
            if depth:
                if m and m.group(1) in NOTED_VARS:
                    self.notes.append('%s:%d: %s %s ... inside a conditional block: skipped (the importer does not '
                                      'evaluate conditionals)' % (path, lineno, m.group(1), m.group(2)))
                continue
            inc = re.match(r'^(-include|sinclude|include)\s+(.*)$', s)
            if inc and not (m and m.group(1) == inc.group(1)):
                for f in (self.expand(inc.group(2)).split() if self.follow else []):
                    f = f if os.path.isabs(f) else os.path.join(self.cwd, f)
                    if not os.path.isfile(f) and inc.group(1) == 'include':
                        self.notes.append('%s:%d: include %s: no such file (skipped)' % (path, lineno, f))
                    self.read(f)
                continue
            if m and ':' not in m.group(1):
                self.assign(m.group(1), m.group(2), m.group(3))

    def assign(self, name, op, val):
        self.assigned.setdefault(name, val)
        if name in self.fixed:
            return
        cur = self.vars.get(name)
        if op == '!=':
            if name in USED_VARS:
                self.notes.append('%s != %s: a shell assignment, not run (empty)' % (name, val))
            self.vars[name] = ('simple', '')
        elif op in (':=', '::='):
            self.vars[name] = ('simple', self.expand(val))
        elif op == '?=':
            if cur is None:
                self.vars[name] = ('rec', val)
        elif op == '+=':
            if cur is None:
                self.vars[name] = ('rec', val)
            elif cur[0] == 'simple':
                self.vars[name] = ('simple', (cur[1] + ' ' + self.expand(val)).strip())
            else:
                self.vars[name] = ('rec', (cur[1] + ' ' + val).strip())
        else:
            self.vars[name] = ('rec', val)

    def value(self, name, depth=0):
        v = self.vars.get(name)
        if v is None:
            return ''
        return v[1] if v[0] == 'simple' else self.expand(v[1], depth + 1)

    def expand(self, s, depth=0):
        if depth > 40:
            return ''
        out, i = [], 0
        while i < len(s):
            c = s[i]
            if c != '$' or i + 1 >= len(s):
                out.append(c)
                i += 1
                continue
            n = s[i + 1]
            if n == '$':
                out.append('$')
                i += 2
            elif n in '({':
                j, d = i + 1, 0
                while j < len(s):
                    if s[j] in '({':
                        d += 1
                    elif s[j] in ')}':
                        d -= 1
                        if d == 0:
                            break
                    j += 1
                out.append(self.ref(s[i + 2:j], depth))
                i = j + 1
            else:
                out.append(self.value(n, depth))
                i += 2
        return ''.join(out)

    def args(self, text, depth):
        parts, d, cur = [], 0, ''
        for ch in text:
            if ch in '({':
                d += 1
            elif ch in ')}':
                d -= 1
            if ch == ',' and d == 0:
                parts.append(cur)
                cur = ''
            else:
                cur += ch
        parts.append(cur)
        return parts

    def path(self, p):
        return os.path.normpath(p if os.path.isabs(p) else os.path.join(self.cwd, p))

    def ref(self, inner, depth):
        m = re.match(r'^([a-z][a-z-]*)\s+(.*)$', inner, re.S)
        if m:
            fn, a = m.group(1), self.args(m.group(2), depth)
            e = lambda k: self.expand(a[k], depth + 1) if k < len(a) else ''
            words = lambda k: e(k).split()
            if fn == 'shell':
                self.notes.append('$(shell %s): not run (empty)' % m.group(2).strip()[:80])
                return ''
            if fn in ('error', 'warning', 'info', 'eval', 'call', 'origin', 'flavor', 'value', 'foreach', 'file'):
                if fn not in ('warning', 'info'):
                    self.notes.append('$(%s ...): not evaluated (empty)' % fn)
                return ''
            if fn == 'subst':
                return e(2).replace(e(0), e(1))
            if fn == 'patsubst':
                return ' '.join(self.patsubst(e(0), e(1), w) for w in words(2))
            if fn == 'strip':
                return ' '.join(words(0))
            if fn == 'findstring':
                return e(0) if e(0) in e(1) else ''
            if fn in ('filter', 'filter-out'):
                pats = words(0)
                hit = lambda w: any(self.patmatch(p, w) is not None for p in pats)
                return ' '.join(w for w in words(1) if hit(w) == (fn == 'filter'))
            if fn == 'sort':
                return ' '.join(sorted(set(words(0))))
            if fn == 'firstword':
                return (words(0) or [''])[0]
            if fn == 'lastword':
                return (words(0) or [''])[-1]
            if fn == 'words':
                return str(len(words(0)))
            if fn == 'word':
                k, ws = e(0).strip(), words(1)
                return ws[int(k) - 1] if k.isdigit() and 0 < int(k) <= len(ws) else ''
            if fn == 'dir':
                return ' '.join((os.path.dirname(w) or '.') + '/' for w in words(0))
            if fn == 'notdir':
                return ' '.join(os.path.basename(w) for w in words(0))
            if fn == 'basename':
                return ' '.join(os.path.splitext(w)[0] for w in words(0))
            if fn == 'suffix':
                return ' '.join(os.path.splitext(w)[1] for w in words(0) if os.path.splitext(w)[1])
            if fn == 'addprefix':
                return ' '.join(e(0) + w for w in words(1))
            if fn == 'addsuffix':
                return ' '.join(w + e(0) for w in words(1))
            if fn in ('abspath', 'realpath'):
                return ' '.join(self.path(w) for w in words(0))
            if fn == 'wildcard':
                import glob
                return ' '.join(sorted(sum((glob.glob(self.path(w)) for w in words(0)), [])))
            if fn == 'if':
                return e(1) if e(0).strip() else e(2)
            if fn == 'or':
                return next((e(k) for k in range(len(a)) if e(k).strip()), '')
            if fn == 'and':
                vals = [e(k) for k in range(len(a))]
                return vals[-1] if all(v.strip() for v in vals) else ''
            self.notes.append('$(%s ...): unknown make function, not evaluated (empty)' % fn)
            return ''
        m = re.match(r'^([^:=]+):([^=]*)=(.*)$', inner)          # substitution reference $(VAR:a=b)
        if m:
            a, b = m.group(2), m.group(3)
            pa, pb = (a, b) if '%' in a else ('%' + a, '%' + b)
            return ' '.join(self.patsubst(pa, pb, w) for w in self.value(self.expand(m.group(1), depth), depth).split())
        return self.value(self.expand(inner, depth), depth)

    @staticmethod
    def patmatch(pat, w):
        if '%' not in pat:
            return '' if pat == w else None
        pre, post = pat.split('%', 1)
        if w.startswith(pre) and w.endswith(post) and len(w) >= len(pre) + len(post):
            return w[len(pre):len(w) - len(post)]
        return None

    def patsubst(self, pat, rep, w):
        stem = self.patmatch(pat, w)
        if stem is None:
            return w
        return rep.replace('%', stem, 1) if '%' in rep else rep

    def get(self, name):
        """The value of a variable, split as a shell splits it (quotes group words)."""
        text = self.value(name)
        try:
            return shlex.split(text)
        except ValueError:
            self.notes.append('%s: unbalanced quotes, split on spaces' % name)
            return text.split()


